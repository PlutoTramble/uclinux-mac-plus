#!/bin/sh
# Host-side checks of the on-Mac toolchain. Runs INSIDE the build container
# (called by build-in-container.sh), needs no emulator:
#
#   1. cpp-host -> cc1-host -> as.c on the tests and on large gcc/*.c files
#   2. differential check: the same GCC 1.42 assembly is also assembled by
#      m68k-elf-as (GNU as, -S) and the code, data, relocations and global
#      symbols must be the same as the ones from as.c
#   3. the cc driver, built for the host, compiles and links every test
#      (cpp-host, cc1-host, as.c, ld.c) to a bFLT with the real libraries
#
# usage: host-check.sh    (/build = user/cc, /gcc = gcc, /linux = uClinux)
#
# Generated by LLM

B=${B:-/build/build}
G=$B/gcc
T=$B/hostcheck
LIBC=${LIBC_INC:-/linux/lib/libc/include}
LINUX_INC=${LINUX_INC:-/linux/linux-2.0.x/include}
TESTS=${TESTS:-/build/tests}
fail=0

rm -rf $T
mkdir -p $T/shim

# the shim for the libc headers, as installed by build.sh
{ cat $LIBC/features.h; cat /build/gcc-features-shim.h; } > $T/shim/features.h

gcc -m32 -O -w /build/as.c -o $T/as-host || exit 1

# the options the cc driver passes to cpp (keep in sync with cc.c)
CPPOPTS="-nostdinc -I$T/shim -I$LIBC -I$LINUX_INC \
 -Dmc68000 -D__mc68000__ -D__m68k__ -Dunix -Dlinux -D__linux__ -D__uClinux__ -DEMBED -D_POSIX_VERSION \
 -D__restrict= -D__restrict__= -D__extension__="

# $1 = source file, $2 = name, $3... = extra cpp options
compile() {
    src=$1; name=$2; shift; shift
    $G/host/cpp-host $CPPOPTS "$@" $src $T/$name.i || return 1
    $G/host/cc1-host $T/$name.i -quiet -dumpbase $name.c -O -o $T/$name.s || return 1
}

# object -> normalized dump: contents, relocations, global symbols
dump() {
    obj=$1
    m68k-elf-nm --defined-only $obj | awk '{print $3}' > $obj.defs
    m68k-elf-objdump -s -j .text -j .data $obj | grep -v 'file format'
    m68k-elf-objdump -r $obj | grep -v 'file format' | awk -v defs=$obj.defs '
        BEGIN { while ((getline l < defs) > 0) d[l] = 1 }
        $2 ~ /^R_68K/ { v = $3; sub(/\+.*/, "", v)
                        if (v in d || v ~ /^\./) v = "<local>"
                        print $1, $2, v; next }
        { print }'
    m68k-elf-nm -g $obj | sed 's/^[0-9a-f]* //' | sort
}

check_asm() {
    name=$1
    $T/as-host -u -o $T/$name.mine.o $T/$name.s || return 1
    m68k-elf-as -m68000 -S --register-prefix-optional -o $T/$name.ref.o $T/$name.s || return 1
    dump $T/$name.mine.o > $T/$name.mine.dump
    dump $T/$name.ref.o > $T/$name.ref.dump
    # a symbol that is only used inside the file may have a different
    # size class for common symbols (as.c: .comm in COMMON); compare the rest
    if ! diff $T/$name.mine.dump $T/$name.ref.dump > $T/$name.diff; then
        head -20 $T/$name.diff
        return 1
    fi
}

echo "== cpp-host + cc1-host + as.c vs m68k-elf-as: tests"
for f in $TESTS/*.c; do
    n=$(basename $f .c)
    if compile $f $n && check_asm $n; then
        echo "ok   $n"
    else
        echo "FAIL $n"; fail=1
    fi
done

# the compiler compiles its own sources: big, K&R, every construct
echo "== large sources (gcc/*.c)"
GINC="-I$G/cross -I$G/gen -I/gcc -I/gcc/config"
for n in ${BIGFILES:-c-typeck c-decl expr stmt combine reload1 cse jump cccp}; do
    extra=-DNULL=0     # expr.c and others rely on stdio.h defining it
    [ $n = cccp ] && extra='-DNULL=0 -DGCC_INCLUDE_DIR="/usr/lib/gcc/include" -DGPLUSPLUS_INCLUDE_DIR="/usr/lib/g++-include"'
    # the generated parser is in /gcc
    if compile /gcc/$n.c big_$n $GINC $extra && check_asm big_$n; then
        echo "ok   $n ($(wc -l < $T/big_$n.s) lines of assembly)"
    else
        echo "FAIL $n"; fail=1
    fi
done

# ---- the cc driver itself: cpp -> cc1 -> as -> ld -> bFLT, as on the Mac ----
echo "== cc driver (host copy) on the tests"
D=$T/drv
mkdir -p $D/bin $D/lib/gcc/include $D/inc $D/tmp
cp $G/host/cpp-host $D/bin/cpp
cp $G/host/cc1-host $D/bin/cc1
cp $T/as-host $D/bin/as
gcc -m32 -O -w /build/ld.c -o $D/bin/ld || exit 1
for l in crt0.o libc.a libm.a libgcc1.a libgcc.a; do cp $B/lib/$l $D/lib/; done
# the headers as build.sh installs them
cp -rL $LIBC/. $D/inc/
cat /build/gcc-features-shim.h >> $D/inc/features.h
cp /gcc/gstdarg.h $D/lib/gcc/include/stdarg.h
cp /gcc/gvarargs.h $D/lib/gcc/include/varargs.h
cp /gcc/stddef.h $D/lib/gcc/include/stddef.h
gcc -m32 -O -w -DCC_BINDIR=\"$D/bin\" -DCC_LIBDIR=\"$D/lib\" \
    -DCC_INCDIR=\"$D/inc\" -DCC_TMPDIR=\"$D/tmp\" /build/cc.c -o $D/cc || exit 1

for n in hello float int64 libc multi; do
    case $n in
    libc)  srcs="$TESTS/libc.c"; opts="-lm" ;;
    multi) srcs="$TESTS/multi_a.c $TESTS/multi_b.c"; opts="" ;;
    *)     srcs="$TESTS/$n.c"; opts="" ;;
    esac
    rm -f $D/t_$n
    if $D/cc $srcs -o $D/t_$n $opts -O 2> $D/t_$n.err \
       && [ "$(head -c 4 $D/t_$n)" = bFLT ]; then
        echo "ok   $n ($(wc -c < $D/t_$n) bytes, bFLT)"
    else
        echo "FAIL $n"; head -20 $D/t_$n.err; fail=1
    fi
done

# -c, -S and -E each stop at their stage and write exactly one file
cd $D/tmp
$D/cc -c $TESTS/hello.c -o h.o && $D/cc -S $TESTS/hello.c -o h.s \
  && $D/cc -E $TESTS/hello.c -o h.i && [ -s h.o ] && [ -s h.s ] && [ -s h.i ] \
  && grep -q _main h.s && grep -q 'int main' h.i \
  && echo "ok   -c -S -E" || { echo "FAIL -c -S -E"; fail=1; }
# an error: non-zero exit, no output, no temporary files left
printf 'int f(void) { return 1 +; }\n' > bad.c
if $D/cc bad.c -o bad 2> bad.err; then
    echo "FAIL error handling (exit 0)"; fail=1
elif [ -e bad ] || [ -n "$(ls $D/tmp | grep -v '^\(bad\|h\)\.')" ]; then
    echo "FAIL error handling (left files: $(ls $D/tmp))"; fail=1
else
    echo "ok   error handling"
fi
cd /

[ $fail = 0 ] && echo "host-check: all checks passed"
exit $fail
