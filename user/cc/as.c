/* line processing                                                     */

static char **lines;
static int nlines;

/* strip comments, copy into buf */
static void clean_line(const char *src, char *buf, int bufsize)
{
    int n = 0, inq = 0;
    const char *p = src;
    const char *first = src;
    while (*first == ' ' || *first == '\t')
        first++;
    if (*first == '|' || *first == '*' || (*first == '#' && first == src))
        { buf[0] = 0; return; }
    for (; *p && n < bufsize - 1; p++) {
        if (inq) {
            if (*p == '\\' && p[1]) {
                buf[n++] = *p++;
                if (n < bufsize - 1)
                    buf[n++] = *p;
                continue;
            }
            if (*p == '"')
                inq = 0;
        } else if (*p == '"') {
            inq = 1;
        } else if (*p == '\'' && p[1] && p[2] == '\'') {
            buf[n++] = *p++;
            buf[n++] = *p++;
            buf[n++] = *p;
            continue;
        } else if (*p == ';') {
            break;
        }
        buf[n++] = *p;
    }
    buf[n] = 0;
}

static void process_line(int ln)
{
    static char buf[1024];
    char *p, *mn, *args;
    struct symbol *labels[4];
    int nlabels = 0, reparse = 0, i;
    unsigned long start;
    int startsect;
    struct lineinfo *li = &linfo[ln];

    linenr = ln + 1;
    if (!final && pass > 0 && li->kind == LK_FIXED) {
        /* size is known, only move the labels */
        cursect = li->sect;
        if (li->label)
            define_label(li->label);
        sects[cursect].pc += li->size;
        if (sects[cursect].pc > sects[cursect].size)
            sects[cursect].size = sects[cursect].pc;
        return;
    }

    clean_line(lines[ln], buf, sizeof(buf));
    p = skipws(buf);

    /* labels */
    for (;;) {
        char *q = p;
        if (!issymstart((unsigned char)*q) && !isdigit((unsigned char)*q))
            break;
        while (issymchar((unsigned char)*q))
            q++;
        if (*q != ':')
            break;
        *q = 0;
        if (nlabels < 4)
            labels[nlabels++] = lookup(p, 1);
        p = skipws(q + 1);
        if (*p == ':')
            p = skipws(p + 1);
    }

    mn = p;
    while (*p && *p != ' ' && *p != '\t' && *p != '=')
        p++;
    if (*p) {
        int is_eq = *p == '=';
        *p++ = 0;
        args = skipws(p);
        if (is_eq) {
            /* name=value */
            set_symbol(mn, args);
            li->kind = LK_REPARSE;
            for (i = 0; i < nlabels; i++)
                define_label(labels[i]);
            return;
        }
    } else {
        args = p;
    }
    if (*args == '=' && *mn) {
        set_symbol(mn, skipws(args + 1));
        li->kind = LK_REPARSE;
        return;
    }
    if (!strcmp(mn, "equ") || !strcmp(mn, "EQU")) {
        /* label equ value */
        if (nlabels == 1) {
            labels[0]->flags &= ~SYM_DEFINED;
            set_symbol(labels[0]->name, args);
        } else {
            error("equ without a label%s", NULL);
        }
        li->kind = LK_REPARSE;
        return;
    }
    {
        /* "name equ value" without a colon */
        char *q = skipws(args);
        if (*mn && (!strncmp(q, "equ", 3) || !strncmp(q, "EQU", 3)) && (q[3] == ' ' || q[3] == '\t')) {
            set_symbol(mn, skipws(q + 3));
            li->kind = LK_REPARSE;
            return;
        }
    }

    startsect = cursect;
    start = sects[cursect].pc;

    if (*mn && !directive(mn, args, &reparse)) {
        /* an instruction: keep it on an even address */
        if (sects[cursect].pc & 1) {
            emit_byte(0);
            reparse = 1;
        }
        start = sects[cursect].pc;
        for (i = 0; i < nlabels; i++)
            define_label(labels[i]);
        if (!instruction(mn, args, ln))
            error("unknown instruction `%s'", mn);
        /* branches can change their size between passes */
        if (mn[0] == 'j' || mn[0] == 'J' || ((mn[0] == 'b' || mn[0] == 'B') && strchr(mn, '.') == NULL))
            reparse = 1;
    } else {
        /* labels of a directive line point at its start (before any
           alignment padding), or into the new section after a switch */
        for (i = 0; i < nlabels; i++) {
            if (cursect == startsect) {
                unsigned long save = sects[cursect].pc;
                sects[cursect].pc = start;
                define_label(labels[i]);
                sects[cursect].pc = save;
            } else {
                define_label(labels[i]);
            }
        }
    }
    if (pass == 0) {
        if (reparse || nlabels > 1 || cursect != startsect) {
            li->kind = LK_REPARSE;
        } else {
            li->kind = LK_FIXED;
            li->sect = (signed char)cursect;
            li->label = nlabels == 1 ? labels[0] : NULL;
            li->size = (unsigned short)(sects[cursect].pc - start);
            if (sects[cursect].pc - start > 0xffff)
                li->kind = LK_REPARSE;
        }
    }
}

static void run_pass(void)
{
    int i;
    changed = 0;
    cur_relax_changed = 0;
    for (i = 0; i < nsects; i++)
        sects[i].pc = 0;
    cursect = find_section(".text", 1);
    for (i = 0; i < nlines; i++)
        process_line(i);
}

