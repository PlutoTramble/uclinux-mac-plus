/*
 * as - a small 68000 assembler for uClinux on the Macintosh Plus.
 *
 * Reads the assembly that GCC 1.42 writes (see gcc/config/tm-uclinux.h:
 * Motorola operand syntax, GNU style directives, jbra/jbsr/jb<cc> branches,
 * .double/.long data) and writes an ELF32 m68k relocatable object, the
 * same format gcc/binutils use, so the objects can be linked together with
 * the libc that was built by gcc 2.95 (see ld.c).
 *
 * Every symbol name that starts with '_' loses that underscore in the
 * object file (GCC 1.42 puts one in front of every C name, gcc 2.95 does
 * not).  Use -u to keep the names as they are.
 *
 * usage: as [-u] [-o out.o] file.s
 *
 * Only plain 68000 instructions are supported (no 68020+, no FPU).
 * Written to be built with gcc 2.95 (C89) as well as a modern host compiler.
 *
 * Generated by LLM
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>

/* ------------------------------------------------------------------ */
/* ELF constants                                                       */

#define ET_REL 1
#define EM_68K 4
#define SHT_NULL 0
#define SHT_PROGBITS 1
#define SHT_SYMTAB 2
#define SHT_STRTAB 3
#define SHT_RELA 4
#define SHT_NOBITS 8
#define SHF_WRITE 1
#define SHF_ALLOC 2
#define SHF_EXECINSTR 4
#define SHN_UNDEF 0
#define SHN_ABS 0xfff1
#define SHN_COMMON 0xfff2
#define STB_LOCAL 0
#define STB_GLOBAL 1
#define STT_NOTYPE 0
#define STT_SECTION 3
#define R_68K_32 1
#define R_68K_16 2
#define R_68K_8 3
#define R_68K_PC32 4
#define R_68K_PC16 5

/* ------------------------------------------------------------------ */
/* data structures                                                     */

#define SECT_ABS (-1)
#define SECT_UND (-2)
#define MAXSECT 16

struct reloc {
    unsigned long off;
    int type;
    struct symbol *sym;     /* NULL: relative to section 'sect' */
    int sect;
    long addend;
};

struct section {
    char *name;
    int type;               /* SHT_PROGBITS or SHT_NOBITS */
    int flags;
    unsigned long pc;       /* current position while assembling */
    unsigned long size;
    unsigned char *data;
    unsigned long cap;
    struct reloc *rel;
    int nrel, caprel;
    int align;
    int shndx, relndx, symndx;
};

#define SYM_GLOBAL  1
#define SYM_DEFINED 2
#define SYM_USED    4       /* referenced by a relocation */
#define SYM_EQU     8       /* defined with .equ/.set/= */
#define SYM_COMMON  16

struct symbol {
    char *name;
    struct symbol *next;    /* hash chain */
    struct symbol *link;    /* list of all symbols */
    int flags;
    int sect;               /* section index, SECT_ABS or SECT_UND */
    long value;
    unsigned long size;     /* for .comm */
    int align;              /* for .comm */
    int defpass;            /* pass number in which it got its value */
    int deflinenr;
    int elfndx;
};

struct expr {
    long v;
    int sect;               /* SECT_ABS, SECT_UND (then sym) or section */
    struct symbol *sym;
    int known;              /* 0 if it used a symbol without a value yet */
};

/* per source line cache, so the relaxation passes are cheap */
#define LK_REPARSE 0
#define LK_FIXED 1
struct lineinfo {
    struct symbol *label;   /* only for LK_FIXED */
    unsigned short size;
    unsigned char kind;
    unsigned char relax;    /* branch size: 0 = .b, 1 = .w, 2 = long */
    unsigned long prevpc;   /* address of a branch in the previous pass */
    signed char sect;       /* section of a LK_FIXED line */
};

static struct section sects[MAXSECT];
static int nsects;
static int cursect;

#define HASHSIZE 1024
static struct symbol *symhash[HASHSIZE];
static struct symbol *symlist, **symtail = &symlist;

static char *srcname;
static int linenr;
static int nerrors;
static int pass;
static int final;           /* 1 in the emitting pass */
static int changed;
static int keep_underscore;
static struct lineinfo *linfo;
static int cur_relax_changed;

static void error(const char *fmt, const char *arg)
{
    if (!final)
        return;             /* errors are reported once, in the last pass */
    fprintf(stderr, "%s:%d: error: ", srcname, linenr);
    fprintf(stderr, fmt, arg ? arg : "");
    fputc('\n', stderr);
    nerrors++;
}

static void fatal(const char *msg)
{
    fprintf(stderr, "as: %s\n", msg);
    exit(1);
}

static void *xmalloc(unsigned long n)
{
    void *p = malloc(n ? n : 1);
    if (!p)
        fatal("out of memory");
    return p;
}

static void *xrealloc(void *p, unsigned long n)
{
    p = realloc(p, n ? n : 1);
    if (!p)
        fatal("out of memory");
    return p;
}

static char *xstrdup(const char *s)
{
    char *p = xmalloc(strlen(s) + 1);
    strcpy(p, s);
    return p;
}

/* ------------------------------------------------------------------ */
/* symbols                                                             */

static unsigned hash(const char *s)
{
    unsigned h = 0;
    while (*s)
        h = h * 31 + (unsigned char)*s++;
    return h % HASHSIZE;
}

static struct symbol *lookup(const char *name, int create)
{
    unsigned h = hash(name);
    struct symbol *s;
    for (s = symhash[h]; s; s = s->next)
        if (!strcmp(s->name, name))
            return s;
    if (!create)
        return NULL;
    s = xmalloc(sizeof(*s));
    memset(s, 0, sizeof(*s));
    s->name = xstrdup(name);
    s->sect = SECT_UND;
    s->defpass = -1;
    s->next = symhash[h];
    symhash[h] = s;
    *symtail = s;
    symtail = &s->link;
    return s;
}

static void define_label(struct symbol *s)
{
    if ((s->flags & SYM_DEFINED) && s->defpass == pass) {
        error("symbol `%s' is already defined", s->name);
        return;
    }
    if (s->flags & SYM_COMMON) {
        error("symbol `%s' is already defined as common", s->name);
        return;
    }
    if (s->sect != cursect || s->value != (long)sects[cursect].pc)
        changed = 1;
    s->flags |= SYM_DEFINED;
    s->sect = cursect;
    s->value = sects[cursect].pc;
    s->defpass = pass;
    s->deflinenr = linenr;
}

/* ------------------------------------------------------------------ */
/* sections and output bytes                                           */

static int find_section(const char *name, int create)
{
    int i;
    for (i = 0; i < nsects; i++)
        if (!strcmp(sects[i].name, name))
            return i;
    if (!create)
        return -1;
    if (nsects >= MAXSECT)
        fatal("too many sections");
    memset(&sects[nsects], 0, sizeof(sects[nsects]));
    sects[nsects].name = xstrdup(name);
    sects[nsects].align = 2;
    if (!strcmp(name, ".bss") || !strncmp(name, ".bss.", 5)) {
        sects[nsects].type = SHT_NOBITS;
        sects[nsects].flags = SHF_ALLOC | SHF_WRITE;
    } else if (!strcmp(name, ".text") || !strncmp(name, ".text.", 6)) {
        sects[nsects].type = SHT_PROGBITS;
        sects[nsects].flags = SHF_ALLOC | SHF_EXECINSTR;
    } else if (!strncmp(name, ".rodata", 7)) {
        sects[nsects].type = SHT_PROGBITS;
        sects[nsects].flags = SHF_ALLOC;
    } else if (!strncmp(name, ".comment", 8) || !strncmp(name, ".note", 5)
               || !strncmp(name, ".debug", 6) || !strncmp(name, ".stab", 5)) {
        sects[nsects].type = SHT_PROGBITS;
        sects[nsects].flags = 0;
    } else {
        sects[nsects].type = SHT_PROGBITS;
        sects[nsects].flags = SHF_ALLOC | SHF_WRITE;
    }
    return nsects++;
}

static void emit_byte(int b)
{
    struct section *s = &sects[cursect];
    if (final && s->type != SHT_NOBITS) {
        if (s->pc >= s->cap) {
            s->cap = s->cap ? s->cap * 2 : 4096;
            while (s->cap <= s->pc)
                s->cap *= 2;
            s->data = xrealloc(s->data, s->cap);
        }
        s->data[s->pc] = (unsigned char)b;
    } else if (final && b != 0) {
        error("non-zero data in %s", s->name);
    }
    s->pc++;
    if (s->pc > s->size)
        s->size = s->pc;
}

static void emit_word(unsigned long w)
{
    emit_byte((int)((w >> 8) & 0xff));
    emit_byte((int)(w & 0xff));
}

static void emit_long(unsigned long l)
{
    emit_word((l >> 16) & 0xffff);
    emit_word(l & 0xffff);
}

static void add_reloc(unsigned long off, int type, struct expr *e)
{
    struct section *s = &sects[cursect];
    struct reloc *r;
    if (!final)
        return;
    if (s->nrel >= s->caprel) {
        s->caprel = s->caprel ? s->caprel * 2 : 64;
        s->rel = xrealloc(s->rel, s->caprel * sizeof(struct reloc));
    }
    r = &s->rel[s->nrel++];
    r->off = off;
    r->type = type;
    r->addend = e->v;
    if (e->sect == SECT_UND) {
        r->sym = e->sym;
        r->sect = SECT_UND;
        e->sym->flags |= SYM_USED;
    } else {
        r->sym = NULL;
        r->sect = e->sect;
    }
}

/* store an expression in a field of 1, 2 or 4 bytes */
static void emit_value(struct expr *e, int size)
{
    if (e->sect != SECT_ABS) {
        add_reloc(sects[cursect].pc, size == 4 ? R_68K_32 : size == 2 ? R_68K_16 : R_68K_8, e);
        if (size == 4)
            emit_long(0);
        else if (size == 2)
            emit_word(0);
        else
            emit_byte(0);
        return;
    }
    if (size == 1) {
        if (e->v < -128 || e->v > 255)
            error("value does not fit in a byte%s", NULL);
        emit_byte((int)(e->v & 0xff));
    } else if (size == 2) {
        if (e->v < -32768L || e->v > 65535L)
            error("value does not fit in a word%s", NULL);
        emit_word((unsigned long)e->v & 0xffff);
    } else {
        emit_long((unsigned long)e->v);
    }
}

/* ------------------------------------------------------------------ */
/* lexical helpers                                                     */

static char *skipws(char *p)
{
    while (*p == ' ' || *p == '\t')
        p++;
    return p;
}

static int issymstart(int c)
{
    return isalpha(c) || c == '_' || c == '.' || c == '$';
}

static int issymchar(int c)
{
    return isalnum(c) || c == '_' || c == '.' || c == '$';
}

/* ------------------------------------------------------------------ */
/* expressions                                                         */

static char *ep;            /* expression parser position */
static int ebad;

static void expr_parse(struct expr *e, int prec);

static void set_abs(struct expr *e, long v)
{
    e->v = v;
    e->sect = SECT_ABS;
    e->sym = NULL;
    e->known = 1;
}

static void expr_primary(struct expr *e)
{
    char name[256];
    int n;
    ep = skipws(ep);
    if (*ep == '(') {
        ep++;
        expr_parse(e, 0);
        ep = skipws(ep);
        if (*ep == ')')
            ep++;
        else
            ebad = 1;
        return;
    }
    if (*ep == '-') {
        ep++;
        expr_primary(e);
        if (e->sect != SECT_ABS)
            ebad = 1;
        e->v = -e->v;
        return;
    }
    if (*ep == '+') {
        ep++;
        expr_primary(e);
        return;
    }
    if (*ep == '~') {
        ep++;
        expr_primary(e);
        if (e->sect != SECT_ABS)
            ebad = 1;
        e->v = ~e->v;
        return;
    }
    if (*ep == '!') {
        ep++;
        expr_primary(e);
        if (e->sect != SECT_ABS)
            ebad = 1;
        e->v = !e->v;
        return;
    }
    if (*ep == '\'') {
        ep++;
        if (*ep == '\\') {
            ep++;
            switch (*ep) {
            case 'n': set_abs(e, '\n'); break;
            case 't': set_abs(e, '\t'); break;
            case 'r': set_abs(e, '\r'); break;
            case '0': set_abs(e, 0); break;
            default: set_abs(e, (unsigned char)*ep); break;
            }
        } else {
            set_abs(e, (unsigned char)*ep);
        }
        if (*ep)
            ep++;
        if (*ep == '\'')
            ep++;
        return;
    }
    if (isdigit((unsigned char)*ep)) {
        unsigned long v = 0;
        if (ep[0] == '0' && (ep[1] == 'x' || ep[1] == 'X')) {
            ep += 2;
            while (isxdigit((unsigned char)*ep)) {
                v = v * 16 + (isdigit((unsigned char)*ep) ? *ep - '0' : (tolower((unsigned char)*ep) - 'a' + 10));
                ep++;
            }
        } else if (ep[0] == '0' && (ep[1] == 'b' || ep[1] == 'B') && (ep[2] == '0' || ep[2] == '1')) {
            ep += 2;
            while (*ep == '0' || *ep == '1')
                v = v * 2 + (*ep++ - '0');
        } else if (ep[0] == '0') {
            while (*ep >= '0' && *ep <= '7')
                v = v * 8 + (*ep++ - '0');
        } else {
            while (isdigit((unsigned char)*ep))
                v = v * 10 + (*ep++ - '0');
        }
        set_abs(e, (long)v);
        return;
    }
    if (*ep == '$' && isxdigit((unsigned char)ep[1])) {
        unsigned long v = 0;
        ep++;
        while (isxdigit((unsigned char)*ep)) {
            v = v * 16 + (isdigit((unsigned char)*ep) ? *ep - '0' : (tolower((unsigned char)*ep) - 'a' + 10));
            ep++;
        }
        set_abs(e, (long)v);
        return;
    }
    if (*ep == '.' && !issymchar((unsigned char)ep[1])) {
        ep++;
        e->v = sects[cursect].pc;
        e->sect = cursect;
        e->sym = NULL;
        e->known = 1;
        return;
    }
    if (issymstart((unsigned char)*ep)) {
        struct symbol *s;
        n = 0;
        while (issymchar((unsigned char)*ep)) {
            if (n < 255)
                name[n++] = *ep;
            ep++;
        }
        name[n] = 0;
        s = lookup(name, 1);
        e->known = 1;
        if ((s->flags & SYM_DEFINED) && !(s->flags & SYM_COMMON)) {
            e->v = s->value;
            e->sect = s->sect;
            e->sym = NULL;
            if (s->defpass != pass)
                e->known = 0;   /* value from the previous pass */
        } else {
            e->v = 0;
            e->sect = SECT_UND;
            e->sym = s;
        }
        return;
    }
    ebad = 1;
    set_abs(e, 0);
}

static int binop(char **pp, int *prec)
{
    char *p = skipws(*pp);
    int op = 0;
    switch (p[0]) {
    case '*': op = '*'; *prec = 5; break;
    case '/': op = '/'; *prec = 5; break;
    case '%': op = '%'; *prec = 5; break;
    case '+': op = '+'; *prec = 4; break;
    case '-': op = '-'; *prec = 4; break;
    case '<': if (p[1] == '<') { op = 'L'; *prec = 3; p++; } break;
    case '>': if (p[1] == '>') { op = 'R'; *prec = 3; p++; } break;
    case '&': op = '&'; *prec = 2; break;
    case '^': op = '^'; *prec = 1; break;
    case '|': op = '|'; *prec = 0; break;
    }
    if (op)
        *pp = p + 1;
    return op;
}

static void expr_parse(struct expr *e, int minprec)
{
    struct expr r;
    int op, prec;
    char *save;
    expr_primary(e);
    for (;;) {
        save = ep;
        op = binop(&ep, &prec);
        if (!op || prec < minprec) {
            ep = save;
            return;
        }
        expr_parse(&r, prec + 1);
        if (!r.known)
            e->known = 0;
        if (op == '+') {
            if (e->sect == SECT_ABS) {
                e->sect = r.sect;
                e->sym = r.sym;
                e->v += r.v;
            } else if (r.sect == SECT_ABS) {
                e->v += r.v;
            } else {
                ebad = 1;
            }
        } else if (op == '-') {
            if (r.sect == SECT_ABS) {
                e->v -= r.v;
            } else if (e->sect == r.sect && e->sect != SECT_UND) {
                e->v -= r.v;
                e->sect = SECT_ABS;
                e->sym = NULL;
            } else {
                ebad = 1;
            }
        } else {
            if (e->sect != SECT_ABS || r.sect != SECT_ABS) {
                ebad = 1;
                continue;
            }
            switch (op) {
            case '*': e->v *= r.v; break;
            case '/': if (r.v) e->v /= r.v; else if (final) ebad = 1; break;
            case '%': if (r.v) e->v %= r.v; else if (final) ebad = 1; break;
            case 'L': e->v = (long)((unsigned long)e->v << r.v); break;
            case 'R': e->v >>= r.v; break;
            case '&': e->v &= r.v; break;
            case '^': e->v ^= r.v; break;
            case '|': e->v |= r.v; break;
            }
        }
    }
}

/* evaluate the whole string s as an expression */
static int eval(char *s, struct expr *e)
{
    ep = s;
    ebad = 0;
    expr_parse(e, 0);
    ep = skipws(ep);
    if (*ep || ebad) {
        error("bad expression `%s'", s);
        set_abs(e, 0);
        return 0;
    }
    return 1;
}

/* does the expression refer to any symbol at all? */
static int has_symbol(const char *s)
{
    const char *p = s;
    while (*p) {
        if (*p == '\'') {
            p++;
            if (*p == '\\')
                p++;
            if (*p)
                p++;
            if (*p == '\'')
                p++;
            continue;
        }
        if (isdigit((unsigned char)*p)) {
            while (isalnum((unsigned char)*p))
                p++;
            continue;
        }
        if (*p == '$' && isxdigit((unsigned char)p[1])) {
            p++;
            while (isxdigit((unsigned char)*p))
                p++;
            continue;
        }
        if (issymstart((unsigned char)*p))
            return 1;
        p++;
    }
    return 0;
}

/* ------------------------------------------------------------------ */
/* operands                                                            */

enum {
    M_DREG, M_AREG, M_IND, M_POSTINC, M_PREDEC, M_DISP, M_INDEX,
    M_ABSW, M_ABSL, M_PCDISP, M_PCINDEX, M_IMM, M_REGLIST,
    M_SR, M_CCR, M_USP
};

struct operand {
    int mode;
    int reg;
    int xreg;               /* index register 0-15 */
    int xlong;
    int mask;               /* register list */
    char *text;             /* expression text (immediate, displacement...) */
    int imm_mask;           /* movem with #mask */
};

/* register number 0-7 = d0-d7, 8-15 = a0-a7, 16 = pc, 17 = sr, 18 = ccr, 19 = usp */
static int parse_reg(const char *s, int len)
{
    char b[8];
    int i;
    if (len < 2 || len > 3)
        return -1;
    for (i = 0; i < len; i++)
        b[i] = (char)tolower((unsigned char)s[i]);
    b[len] = 0;
    if (len == 2 && b[0] == 'd' && b[1] >= '0' && b[1] <= '7')
        return b[1] - '0';
    if (len == 2 && b[0] == 'a' && b[1] >= '0' && b[1] <= '7')
        return 8 + b[1] - '0';
    if (!strcmp(b, "sp"))
        return 15;
    if (!strcmp(b, "fp"))
        return 14;
    if (!strcmp(b, "pc"))
        return 16;
    if (!strcmp(b, "sr"))
        return 17;
    if (!strcmp(b, "ccr"))
        return 18;
    if (!strcmp(b, "usp"))
        return 19;
    return -1;
}

static int whole_reg(const char *s)
{
    while (*s == ' ' || *s == '\t')
        s++;
    {
        int len = (int)strlen(s);
        while (len > 0 && (s[len - 1] == ' ' || s[len - 1] == '\t'))
            len--;
        return parse_reg(s, len);
    }
}

/* register list like d0-d3/a2/a5; returns mask or -1 */
static int parse_reglist(const char *s)
{
    int mask = 0;
    const char *p = s;
    for (;;) {
        int r1, r2, len;
        const char *q;
        p = skipws((char *)p);
        q = p;
        while (isalnum((unsigned char)*q))
            q++;
        len = (int)(q - p);
        r1 = parse_reg(p, len);
        if (r1 < 0 || r1 > 15)
            return -1;
        p = skipws((char *)q);
        r2 = r1;
        if (*p == '-') {
            p = skipws((char *)p + 1);
            q = p;
            while (isalnum((unsigned char)*q))
                q++;
            r2 = parse_reg(p, (int)(q - p));
            if (r2 < 0 || r2 > 15 || r2 < r1)
                return -1;
            p = skipws((char *)q);
        }
        while (r1 <= r2)
            mask |= 1 << r1++;
        if (*p == '/') {
            p++;
            continue;
        }
        if (*p == 0)
            return mask;
        return -1;
    }
}

/* parse an index register "d1", "d1.l", "a0.w", "d2.l*1" */
static int parse_index(char *s, struct operand *op)
{
    char *p = skipws(s), *q;
    int r;
    q = p;
    while (isalnum((unsigned char)*q))
        q++;
    r = parse_reg(p, (int)(q - p));
    if (r < 0 || r > 15)
        return 0;
    op->xreg = r;
    op->xlong = 0;
    p = q;
    if (*p == '.') {
        if (tolower((unsigned char)p[1]) == 'l')
            op->xlong = 1;
        else if (tolower((unsigned char)p[1]) != 'w')
            return 0;
        p += 2;
    }
    if (*p == '*') {
        if (p[1] != '1')
            return 0;
        p += 2;
    }
    p = skipws(p);
    return *p == 0;
}

/* split s at top level commas into at most max parts (modifies s) */
static int split_commas(char *s, char **parts, int max)
{
    int n = 0, depth = 0, inq = 0;
    char *p = s;
    parts[n++] = s;
    for (; *p; p++) {
        if (inq) {
            if (*p == '\\' && p[1])
                p++;
            else if (*p == inq)
                inq = 0;
            continue;
        }
        if (*p == '"' || *p == '\'') {
            if (*p == '\'' && p[1] && p[2] == '\'')
                { p += 2; continue; }
            if (*p == '"')
                inq = *p;
            continue;
        }
        if (*p == '(')
            depth++;
        else if (*p == ')')
            depth--;
        else if (*p == ',' && depth == 0) {
            *p = 0;
            if (n >= max)
                return -1;
            parts[n++] = p + 1;
        }
    }
    return n;
}

static char *trim(char *s)
{
    char *e;
    s = skipws(s);
    e = s + strlen(s);
    while (e > s && (e[-1] == ' ' || e[-1] == '\t'))
        e--;
    *e = 0;
    return s;
}

static char zero_text[] = "0";

/* "L204.b" in (L204.b,pc,d0.l): drop the size suffix of the displacement */
static char *strip_size(char *t)
{
    int n = (int)strlen(t);
    if (n > 2 && t[n - 2] == '.' && strchr("bwlBWL", t[n - 1]))
        t[n - 2] = 0;
    return t;
}

/* parse "(inner)" contents into op; inner is modified */
static int parse_paren(char *inner, char *disp, struct operand *op)
{
    char *parts[3];
    int n, r;
    n = split_commas(inner, parts, 3);
    if (n < 1)
        return 0;
    parts[0] = trim(parts[0]);
    if (n >= 2)
        parts[1] = trim(parts[1]);
    if (n >= 3)
        parts[2] = trim(parts[2]);
    if (disp) {
        /* d(An), d(An,Xn), d(pc), d(pc,Xn) */
        r = whole_reg(parts[0]);
        if (r < 8 || r > 16 || n > 2)
            return 0;
        op->text = disp;
        if (n == 1) {
            op->mode = r == 16 ? M_PCDISP : M_DISP;
            op->reg = r & 7;
            return 1;
        }
        if (!parse_index(parts[1], op))
            return 0;
        op->mode = r == 16 ? M_PCINDEX : M_INDEX;
        op->reg = r & 7;
        return 1;
    }
    if (n == 1) {
        r = whole_reg(parts[0]);
        if (r >= 8 && r <= 15) {
            op->mode = M_IND;
            op->reg = r - 8;
            return 1;
        }
        if (r == 16) {
            op->mode = M_PCDISP;
            op->text = zero_text;
            return 1;
        }
        return 0;
    }
    r = whole_reg(parts[1]);
    if (n == 2 && r >= 8 && r <= 16) {
        /* (d,An) or (d,pc) */
        op->mode = r == 16 ? M_PCDISP : M_DISP;
        op->reg = r & 7;
        op->text = parts[0];
        return 1;
    }
    r = whole_reg(parts[0]);
    if (n == 2 && r >= 8 && r <= 16) {
        /* (An,Xn) */
        if (!parse_index(parts[1], op))
            return 0;
        op->mode = r == 16 ? M_PCINDEX : M_INDEX;
        op->reg = r & 7;
        op->text = zero_text;
        return 1;
    }
    if (n == 3) {
        r = whole_reg(parts[1]);
        if (r < 8 || r > 16)
            return 0;
        if (!parse_index(parts[2], op))
            return 0;
        op->mode = r == 16 ? M_PCINDEX : M_INDEX;
        op->reg = r & 7;
        op->text = strip_size(parts[0]);
        return 1;
    }
    return 0;
}

static int parse_operand(char *s, struct operand *op)
{
    int len, r;
    char *p;
    memset(op, 0, sizeof(*op));
    s = trim(s);
    len = (int)strlen(s);
    if (!len)
        return 0;
    if (*s == '#') {
        op->mode = M_IMM;
        op->text = s + 1;
        return 1;
    }
    r = parse_reg(s, len);
    if (r >= 0) {
        if (r < 8) { op->mode = M_DREG; op->reg = r; }
        else if (r < 16) { op->mode = M_AREG; op->reg = r - 8; }
        else if (r == 17) op->mode = M_SR;
        else if (r == 18) op->mode = M_CCR;
        else if (r == 19) op->mode = M_USP;
        else return 0;
        return 1;
    }
    if (s[0] == '-' && s[1] == '(' && s[len - 1] == ')') {
        char tmp[16];
        if (len - 3 < 15) {
            memcpy(tmp, s + 2, len - 3);
            tmp[len - 3] = 0;
            r = whole_reg(tmp);
            if (r >= 8 && r <= 15) {
                op->mode = M_PREDEC;
                op->reg = r - 8;
                return 1;
            }
        }
    }
    if (s[0] == '(' && s[len - 1] == '+' && s[len - 2] == ')') {
        char tmp[16];
        if (len - 3 < 15) {
            memcpy(tmp, s + 1, len - 3);
            tmp[len - 3] = 0;
            r = whole_reg(tmp);
            if (r >= 8 && r <= 15) {
                op->mode = M_POSTINC;
                op->reg = r - 8;
                return 1;
            }
        }
    }
    if (strchr(s, '/') || (strchr(s, '-') && !strchr(s, '('))) {
        int m = parse_reglist(s);
        if (m >= 0) {
            op->mode = M_REGLIST;
            op->mask = m;
            return 1;
        }
    }
    if (s[len - 1] == ')') {
        /* find the matching '(' */
        int depth = 0;
        p = s + len - 1;
        for (; p >= s; p--) {
            if (*p == ')')
                depth++;
            else if (*p == '(') {
                if (--depth == 0)
                    break;
            }
        }
        if (p >= s) {
            char *inner = p + 1;
            s[len - 1] = 0;
            if (p == s) {
                char *copy = xstrdup(inner);
                if (parse_paren(inner, NULL, op)) {
                    free(copy);
                    return 1;
                }
                /* plain parenthesized expression: absolute */
                strcpy(inner, copy);
                free(copy);
                s[len - 1] = ')';
            } else {
                char *copy = xstrdup(inner);
                *p = 0;
                if (parse_paren(inner, s, op)) {
                    free(copy);
                    return 1;
                }
                *p = '(';
                strcpy(inner, copy);
                free(copy);
                s[len - 1] = ')';
            }
        }
    }
    /* absolute address, optionally with .w/.l */
    op->mode = M_ABSL;
    op->reg = -1;
    if (len > 2 && s[len - 2] == '.' && (tolower((unsigned char)s[len - 1]) == 'w' || tolower((unsigned char)s[len - 1]) == 'l')) {
        op->reg = tolower((unsigned char)s[len - 1]) == 'w' ? 1 : 2;
        s[len - 2] = 0;
    }
    op->text = s;
    return 1;
}

/* ------------------------------------------------------------------ */
/* effective address encoding                                          */

#define EA_DATA     1       /* data addressing modes */
#define EA_MEM      2
#define EA_CONTROL  4
#define EA_ALTER    8

static int sizecode;        /* 0 = byte, 1 = word, 2 = long */
static int opsize;          /* 1, 2 or 4 */

static int ea_class(struct operand *op)
{
    switch (op->mode) {
    case M_DREG: return EA_DATA | EA_ALTER;
    case M_AREG: return EA_ALTER;
    case M_IND: return EA_DATA | EA_MEM | EA_CONTROL | EA_ALTER;
    case M_POSTINC: case M_PREDEC: return EA_DATA | EA_MEM | EA_ALTER;
    case M_DISP: case M_INDEX: case M_ABSW: case M_ABSL:
        return EA_DATA | EA_MEM | EA_CONTROL | EA_ALTER;
    case M_PCDISP: case M_PCINDEX: return EA_DATA | EA_MEM | EA_CONTROL;
    case M_IMM: return EA_DATA | EA_MEM;
    }
    return 0;
}

/* decide abs.w / abs.l once; the decision never depends on symbol values */
static void fix_abs(struct operand *op)
{
    if (op->mode != M_ABSL)
        return;
    if (op->reg == 1) {
        op->mode = M_ABSW;
    } else if (op->reg == -1 && !has_symbol(op->text)) {
        struct expr e;
        eval(op->text, &e);
        if (e.sect == SECT_ABS && e.v >= -32768L && e.v <= 32767L)
            op->mode = M_ABSW;
    }
}

static int ea_bits(struct operand *op)
{
    switch (op->mode) {
    case M_DREG: return op->reg;
    case M_AREG: return 8 | op->reg;
    case M_IND: return 16 | op->reg;
    case M_POSTINC: return 24 | op->reg;
    case M_PREDEC: return 32 | op->reg;
    case M_DISP: return 40 | op->reg;
    case M_INDEX: return 48 | op->reg;
    case M_ABSW: return 56;
    case M_ABSL: return 57;
    case M_PCDISP: return 58;
    case M_PCINDEX: return 59;
    case M_IMM: return 60;
    }
    return 0;
}

/* emit the extension words of an effective address; pc must point at them */
static void ea_ext(struct operand *op, int size)
{
    struct expr e;
    unsigned long here = sects[cursect].pc;
    switch (op->mode) {
    case M_DISP:
        eval(op->text, &e);
        if (e.sect != SECT_ABS) {
            error("displacement is not a constant%s", NULL);
            set_abs(&e, 0);
        }
        if (e.v < -32768L || e.v > 32767L)
            error("displacement out of range%s", NULL);
        emit_word((unsigned long)e.v & 0xffff);
        break;
    case M_INDEX:
    case M_PCINDEX:
        eval(op->text, &e);
        if (op->mode == M_PCINDEX && e.sect == cursect) {
            e.v -= (long)here;
            e.sect = SECT_ABS;
        }
        if (e.sect != SECT_ABS) {
            error("index displacement is not a constant%s", NULL);
            set_abs(&e, 0);
        }
        if (e.v < -128 || e.v > 127)
            error("index displacement out of range%s", NULL);
        emit_word(((unsigned long)op->xreg << 12) | (op->xlong ? 0x800 : 0) | ((unsigned long)e.v & 0xff));
        break;
    case M_ABSW:
        eval(op->text, &e);
        emit_value(&e, 2);
        break;
    case M_ABSL:
        eval(op->text, &e);
        emit_value(&e, 4);
        break;
    case M_PCDISP:
        eval(op->text, &e);
        if (e.sect == cursect) {
            e.v -= (long)here;
            e.sect = SECT_ABS;
            if (e.v < -32768L || e.v > 32767L)
                error("pc relative displacement out of range%s", NULL);
            emit_word((unsigned long)e.v & 0xffff);
        } else if (e.sect == SECT_ABS) {
            emit_word((unsigned long)e.v & 0xffff);
        } else {
            add_reloc(here, R_68K_PC16, &e);
            emit_word(0);
        }
        break;
    case M_IMM:
        eval(op->text, &e);
        if (size == 4) {
            emit_value(&e, 4);
        } else if (size == 2) {
            emit_value(&e, 2);
        } else {
            if (e.sect != SECT_ABS)
                error("byte immediate is not a constant%s", NULL);
            else if (e.v < -128 || e.v > 255)
                error("immediate value does not fit in a byte%s", NULL);
            emit_word((unsigned long)e.v & 0xff);
        }
        break;
    }
}

/* an instruction word followed by the extension words of up to two EAs */
static void emit_op(unsigned long opcode, struct operand *src, int srcsize, struct operand *dst, int dstsize)
{
    emit_word(opcode);
    if (src)
        ea_ext(src, srcsize);
    if (dst)
        ea_ext(dst, dstsize);
}

/* is the immediate a constant that is known at this point of every pass? */
static int quick_value(struct operand *op, long *v)
{
    struct expr e;
    if (op->mode != M_IMM)
        return 0;
    if (has_symbol(op->text)) {
        /* only symbols defined earlier with a constant value qualify */
        char *p = op->text;
        while (*p) {
            if (issymstart((unsigned char)*p) && !(*p == '$' && isxdigit((unsigned char)p[1]))) {
                char name[256];
                int n = 0;
                struct symbol *s;
                while (issymchar((unsigned char)*p)) {
                    if (n < 255)
                        name[n++] = *p;
                    p++;
                }
                name[n] = 0;
                s = lookup(name, 0);
                if (!s || !(s->flags & SYM_EQU) || s->sect != SECT_ABS || s->defpass != pass || s->deflinenr >= linenr)
                    return 0;
            } else if (isdigit((unsigned char)*p)) {
                while (isalnum((unsigned char)*p))
                    p++;
            } else {
                p++;
            }
        }
    }
    eval(op->text, &e);
    if (e.sect != SECT_ABS)
        return 0;
    *v = e.v;
    return 1;
}

