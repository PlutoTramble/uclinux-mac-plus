static int parse_string(char **pp, int (*out)(int))
{
    char *p = skipws(*pp);
    if (*p != '"')
        return 0;
    p++;
    while (*p && *p != '"') {
        int c = (unsigned char)*p++;
        if (c == '\\') {
            c = (unsigned char)*p++;
            switch (c) {
            case 'n': c = '\n'; break;
            case 't': c = '\t'; break;
            case 'r': c = '\r'; break;
            case 'b': c = '\b'; break;
            case 'f': c = '\f'; break;
            case 'a': c = 7; break;
            case 'v': c = 11; break;
            case 'x': {
                int v = 0;
                while (isxdigit((unsigned char)*p)) {
                    v = v * 16 + (isdigit((unsigned char)*p) ? *p - '0' : tolower((unsigned char)*p) - 'a' + 10);
                    p++;
                }
                c = v & 0xff;
                break;
            }
            default:
                if (c >= '0' && c <= '7') {
                    int v = c - '0', n = 1;
                    while (n < 3 && *p >= '0' && *p <= '7') {
                        v = v * 8 + (*p++ - '0');
                        n++;
                    }
                    c = v & 0xff;
                }
                break;
            }
        }
        out(c);
    }
    if (*p == '"')
        p++;
    *pp = p;
    return 1;
}

static int out_byte(int c)
{
    emit_byte(c);
    return 0;
}

static void do_align(long n, int fill)
{
    if (n < 1)
        n = 1;
    if ((n & (n - 1)) != 0) {
        error("alignment is not a power of two%s", NULL);
        return;
    }
    if (n > sects[cursect].align)
        sects[cursect].align = (int)n;
    while (sects[cursect].pc % n)
        emit_byte(fill);
}

static void data_list(char *args, int size)
{
    char *parts[256];
    int n, i;
    struct expr e;
    n = split_commas(args, parts, 256);
    if (n < 0) {
        error("too many values on one line%s", NULL);
        return;
    }
    for (i = 0; i < n; i++) {
        char *p = trim(parts[i]);
        if (size == 1 && *p == '"') {
            parse_string(&p, out_byte);
            continue;
        }
        if (!*p)
            continue;
        eval(p, &e);
        emit_value(&e, size);
    }
}

/* .double / .float: GCC writes 0d1.5e+00 (also 0f, 0r prefixes) */
static void float_list(char *args, int size)
{
    char *parts[64];
    int n, i, j, little;
    unsigned short one = 1;
    unsigned char b[8];
    n = split_commas(args, parts, 64);
    if (n < 0) {
        error("too many values on one line%s", NULL);
        return;
    }
    little = *(unsigned char *)&one;
    for (i = 0; i < n; i++) {
        char *p = trim(parts[i]);
        double v;
        if (!*p)
            continue;
        if (p[0] == '0' && strchr("fFdDrReE", p[1]) && p[1]
            && (isdigit((unsigned char)p[2]) || p[2] == '-' || p[2] == '+' || p[2] == '.'))
            p += 2;
        v = strtod(p, NULL);
        if (size == 4) {
            float f = (float)v;
            memcpy(b, &f, 4);
        } else {
            memcpy(b, &v, 8);
        }
        for (j = 0; j < size; j++)
            emit_byte(little ? b[size - 1 - j] : b[j]);
    }
}

static void set_symbol(char *name, char *valtext)
{
    struct symbol *s = lookup(name, 1);
    struct expr e;
    eval(valtext, &e);
    if ((s->flags & SYM_DEFINED) && !(s->flags & SYM_EQU)) {
        error("symbol `%s' is already defined", name);
        return;
    }
    if (e.sect == SECT_UND) {
        error("symbol `%s' is set to an undefined value", name);
        return;
    }
    if (s->sect != e.sect || s->value != e.v)
        changed = 1;
    s->flags |= SYM_DEFINED | SYM_EQU;
    s->sect = e.sect;
    s->value = e.v;
    s->defpass = pass;
    s->deflinenr = linenr;
}

static void comm(char *args, int local)
{
    char *parts[3];
    int n;
    struct symbol *s;
    struct expr e;
    long align = 0;
    n = split_commas(args, parts, 3);
    if (n < 2) {
        error("bad .comm/.lcomm%s", NULL);
        return;
    }
    s = lookup(trim(parts[0]), 1);
    eval(trim(parts[1]), &e);
    if (n == 3) {
        struct expr a;
        eval(trim(parts[2]), &a);
        align = a.v;
    }
    if (!local) {
        if ((s->flags & SYM_DEFINED) && !(s->flags & SYM_COMMON)) {
            error("symbol `%s' is already defined", s->name);
            return;
        }
        s->flags |= SYM_COMMON | SYM_GLOBAL;
        if ((unsigned long)e.v > s->size)
            s->size = e.v;
        s->align = align ? (int)align : (e.v >= 4 ? 4 : e.v >= 2 ? 2 : 1);
        if (s->align > 2)
            s->align = 2;   /* 68000: 2 is enough, and what gcc uses */
        return;
    }
    {
        int save = cursect;
        cursect = find_section(".bss", 1);
        if (align > 1)
            do_align(align, 0);
        else if (e.v > 1)
            do_align(2, 0);
        define_label(s);
        sects[cursect].pc += e.v;
        if (sects[cursect].pc > sects[cursect].size)
            sects[cursect].size = sects[cursect].pc;
        cursect = save;
    }
}

/* returns 1 if it was a directive; *reparse is set if the line's size may
   change between passes */
static int directive(char *mn, char *args, int *reparse)
{
    char d[32];
    int i;
    struct expr e;
    if (strlen(mn) >= sizeof(d))
        return 0;
    for (i = 0; mn[i]; i++)
        d[i] = (char)tolower((unsigned char)mn[i]);
    d[i] = 0;
    if (d[0] == '.')
        memmove(d, d + 1, strlen(d));
    else if (strcmp(d, "dc.b") && strcmp(d, "dc.w") && strcmp(d, "dc.l") && strcmp(d, "dc")
             && strcmp(d, "ds.b") && strcmp(d, "ds.w") && strcmp(d, "ds.l") && strcmp(d, "ds")
             && strcmp(d, "even") && strcmp(d, "xdef") && strcmp(d, "xref") && strcmp(d, "public")
             && strcmp(d, "section") && strcmp(d, "cnop"))
        return 0;

    if (!strcmp(d, "text") || !strcmp(d, "data") || !strcmp(d, "bss")) {
        char n[8];
        n[0] = '.';
        strcpy(n + 1, d);
        cursect = find_section(n, 1);
        *reparse = 1;
        return 1;
    }
    if (!strcmp(d, "section")) {
        char *parts[4], *name;
        int n = split_commas(args, parts, 4);
        if (n < 1) {
            error("bad .section%s", NULL);
            return 1;
        }
        name = trim(parts[0]);
        if (*name == '"') {
            name++;
            if (name[strlen(name) - 1] == '"')
                name[strlen(name) - 1] = 0;
        }
        if (!strcmp(name, "code") || !strcmp(name, "CODE"))
            name = ".text";
        else if (!strcmp(name, "data") || !strcmp(name, "DATA"))
            name = ".data";
        else if (!strcmp(name, "bss") || !strcmp(name, "BSS"))
            name = ".bss";
        cursect = find_section(name, 1);
        *reparse = 1;
        return 1;
    }
    if (!strcmp(d, "global") || !strcmp(d, "globl") || !strcmp(d, "xdef") || !strcmp(d, "public")) {
        char *parts[64];
        int n = split_commas(args, parts, 64);
        for (i = 0; i < n; i++)
            lookup(trim(parts[i]), 1)->flags |= SYM_GLOBAL;
        return 1;
    }
    if (!strcmp(d, "extern") || !strcmp(d, "xref") || !strcmp(d, "file") || !strcmp(d, "ident")
        || !strcmp(d, "type") || !strcmp(d, "size") || !strcmp(d, "local") || !strcmp(d, "weak")
        || !strcmp(d, "version") || !strcmp(d, "cpu") || !strcmp(d, "machine") || !strcmp(d, "end")) {
        return 1;
    }
    if (!strcmp(d, "align") || !strcmp(d, "balign") || !strcmp(d, "p2align") || !strcmp(d, "even") || !strcmp(d, "cnop")) {
        char *parts[3];
        int n = 0;
        long fill = 0;
        if (!strcmp(d, "even")) {
            do_align(2, 0);
        } else if (!strcmp(d, "cnop")) {
            n = split_commas(args, parts, 3);
            if (n == 2) {
                eval(trim(parts[1]), &e);
                do_align(e.v, 0);
            }
        } else {
            n = split_commas(args, parts, 3);
            eval(trim(parts[0]), &e);
            if (n >= 2 && *trim(parts[1])) {
                struct expr f;
                eval(trim(parts[1]), &f);
                fill = f.v;
            }
            if (!strcmp(d, "p2align"))
                e.v = 1L << e.v;
            do_align(e.v, (int)fill);
        }
        *reparse = 1;
        return 1;
    }
    if (!strcmp(d, "byte") || !strcmp(d, "dc.b")) {
        data_list(args, 1);
        return 1;
    }
    if (!strcmp(d, "short") || !strcmp(d, "word") || !strcmp(d, "hword") || !strcmp(d, "dc.w") || !strcmp(d, "dc")) {
        data_list(args, 2);
        return 1;
    }
    if (!strcmp(d, "long") || !strcmp(d, "int") || !strcmp(d, "dc.l")) {
        data_list(args, 4);
        return 1;
    }
    if (!strcmp(d, "double")) {
        float_list(args, 8);
        return 1;
    }
    if (!strcmp(d, "float") || !strcmp(d, "single")) {
        float_list(args, 4);
        return 1;
    }
    if (!strcmp(d, "ascii") || !strcmp(d, "asciz") || !strcmp(d, "string")) {
        char *p = args;
        for (;;) {
            p = skipws(p);
            if (!parse_string(&p, out_byte)) {
                error("string expected%s", NULL);
                break;
            }
            if (d[1] != 's' || d[4] != 'i' || d[5])  /* not plain .ascii */
                if (strcmp(d, "ascii"))
                    emit_byte(0);
            p = skipws(p);
            if (*p != ',')
                break;
            p++;
        }
        return 1;
    }
    if (!strcmp(d, "space") || !strcmp(d, "skip") || !strcmp(d, "zero") || !strncmp(d, "ds", 2)) {
        char *parts[3];
        int n = split_commas(args, parts, 3);
        long fill = 0, cnt, unit = 1;
        if (!strcmp(d, "ds.w") || !strcmp(d, "ds"))
            unit = 2;
        else if (!strcmp(d, "ds.l"))
            unit = 4;
        eval(trim(parts[0]), &e);
        if (e.sect != SECT_ABS) {
            error("size of .space is not a constant%s", NULL);
            return 1;
        }
        if (n >= 2) {
            struct expr f;
            eval(trim(parts[1]), &f);
            fill = f.v;
        }
        if (has_symbol(parts[0]))
            *reparse = 1;
        for (cnt = e.v * unit; cnt > 0; cnt--)
            emit_byte((int)fill);
        return 1;
    }
    if (!strcmp(d, "equ") || !strcmp(d, "set")) {
        char *parts[2];
        if (split_commas(args, parts, 2) != 2) {
            error("bad .equ%s", NULL);
            return 1;
        }
        set_symbol(trim(parts[0]), trim(parts[1]));
        *reparse = 1;
        return 1;
    }
    if (!strcmp(d, "comm") || !strcmp(d, "lcomm")) {
        comm(args, d[0] == 'l');
        *reparse = 1;
        return 1;
    }
    if (!strcmp(d, "org")) {
        error("`.org' is not supported%s", NULL);
        return 1;
    }
    error("unknown directive `%s'", mn);
    return 1;
}

