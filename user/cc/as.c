/* instructions                                                        */

static const char *ccnames[] = {
    "t", "f", "hi", "ls", "cc", "cs", "ne", "eq",
    "vc", "vs", "pl", "mi", "ge", "lt", "gt", "le"
};

static int cond_code(const char *s)
{
    int i;
    if (!strcmp(s, "hs")) return 4;
    if (!strcmp(s, "lo")) return 5;
    for (i = 0; i < 16; i++)
        if (!strcmp(s, ccnames[i]))
            return i;
    return -1;
}

static void bad_operands(const char *mn)
{
    error("invalid operands for `%s'", mn);
}

static int is_alterable_mem(struct operand *op)
{
    int c = ea_class(op);
    return (c & EA_MEM) && (c & EA_ALTER);
}

static int is_data_alterable(struct operand *op)
{
    int c = ea_class(op);
    return (c & EA_DATA) && (c & EA_ALTER);
}

/* branches: target expression, condition (0 = bra, 1 = bsr, 2..15 = Bcc);
   forced: -1 relax, 0 = .s, 1 = .w */
static void do_branch(char *target, int cond, int forced, int line)
{
    struct expr e;
    unsigned long here = sects[cursect].pc;
    int level;
    long disp = 0;
    eval(target, &e);
    if (pass == 0 && e.sect == SECT_UND && forced < 0) {
        /* forward label, not known yet: start with the smallest branch,
           later passes only grow it (so the result is the shortest) */
        level = 0;
    } else if (e.sect != cursect) {
        level = 2;
    } else {
        /* A forward label has its value from the previous pass: measure from
           the address the branch had in that pass too, or the estimate is
           shifted by every branch that grew before this one. */
        if (!e.known && !final && pass > 0)
            disp = e.v - (long)(linfo[line].prevpc + 2);
        else
            disp = e.v - (long)(here + 2);
        if (forced >= 0) {
            level = forced;
        } else {
            /* values of forward labels come from the previous pass; sizes
               only ever grow, so this converges */
            level = linfo[line].relax;
            {
                int need;
                if (disp >= -128 && disp <= 127 && disp != 0)
                    need = 0;
                else if (disp >= -32768L && disp <= 32767L)
                    need = 1;
                else
                    need = 2;
                if (need > level) {
                    level = need;
                    linfo[line].relax = (unsigned char)level;
                    cur_relax_changed = 1;
                }
            }
        }
    }
    linfo[line].prevpc = here;
    if (forced >= 0 && level == 2) {
        error("branch target is not in this section%s", NULL);
        level = forced;
    }
    if (level == 0) {
        if (final && (disp < -128 || disp > 127 || disp == 0))
            error("short branch out of range%s", NULL);
        emit_word(0x6000 | (cond << 8) | ((unsigned long)disp & 0xff));
    } else if (level == 1) {
        if (final && (disp < -32768L || disp > 32767L))
            error("branch out of range%s", NULL);
        emit_word(0x6000 | (cond << 8));
        emit_word((unsigned long)disp & 0xffff);
    } else {
        if (cond >= 2) {
            /* inverted short branch over a jmp */
            emit_word(0x6000 | ((cond ^ 1) << 8) | 6);
        }
        emit_word(cond == 1 ? 0x4eb9 : 0x4ef9);
        emit_value(&e, 4);
    }
}

static int size_from_suffix(int c, int deflt)
{
    switch (c) {
    case 'b': return 0;
    case 'w': return 1;
    case 'l': return 2;
    case 's': return 0;
    case 0: return deflt;
    }
    return -1;
}

static void set_size(int sc)
{
    sizecode = sc;
    opsize = sc == 0 ? 1 : sc == 1 ? 2 : 4;
}

/* returns 0 if the mnemonic is unknown */
static int instruction(char *mn, char *args, int line)
{
    char base[32], *dot;
    int sfx = 0, nops, i, cc;
    char *parts[3];
    struct operand o[2], *s = &o[0], *d = &o[1];
    unsigned long opc;
    long v;

    if (strlen(mn) >= sizeof(base))
        return 0;
    for (i = 0; mn[i]; i++)
        base[i] = (char)tolower((unsigned char)mn[i]);
    base[i] = 0;
    dot = strchr(base, '.');
    if (dot) {
        *dot = 0;
        sfx = dot[1];
        if (!sfx || dot[2])
            return 0;
    }

    nops = 0;
    if (args && *skipws(args)) {
        nops = split_commas(args, parts, 2);
        if (nops < 0) {
            error("too many operands%s", NULL);
            return 1;
        }
    }

    /* branches first, their operand is just an expression */
    if (base[0] == 'j' && (!strcmp(base, "jbra") || !strcmp(base, "jbsr") || !strcmp(base, "jra")
                           || (cond_code(base + 1) >= 2 && strlen(base) <= 3)
                           || (base[1] == 'b' && strlen(base) <= 4 && cond_code(base + 2) >= 2))) {
        if (nops != 1) { bad_operands(mn); return 1; }
        cc = (!strcmp(base, "jbra") || !strcmp(base, "jra")) ? 0 : !strcmp(base, "jbsr") ? 1
             : base[1] == 'b' ? cond_code(base + 2) : cond_code(base + 1);
        do_branch(trim(parts[0]), cc, -1, line);
        return 1;
    }
    if (base[0] == 'b' && (!strcmp(base, "bra") || !strcmp(base, "bsr") || (strlen(base) == 3 && cond_code(base + 1) >= 2))) {
        int forced = -1;
        if (nops != 1) { bad_operands(mn); return 1; }
        cc = !strcmp(base, "bra") ? 0 : !strcmp(base, "bsr") ? 1 : cond_code(base + 1);
        if (sfx == 's' || sfx == 'b')
            forced = 0;
        else if (sfx == 'w')
            forced = 1;
        else if (sfx)
            { error("68020 branch sizes are not supported%s", NULL); forced = 1; }
        do_branch(trim(parts[0]), cc, forced, line);
        return 1;
    }
    if (base[0] == 'd' && base[1] == 'b' && (!strcmp(base, "dbra") || cond_code(base + 2) >= 0)) {
        struct expr e;
        unsigned long here;
        cc = !strcmp(base, "dbra") ? 1 : cond_code(base + 2);
        if (nops != 2 || !parse_operand(parts[0], s) || s->mode != M_DREG) { bad_operands(mn); return 1; }
        emit_word(0x50c8 | (cc << 8) | s->reg);
        here = sects[cursect].pc;
        eval(trim(parts[1]), &e);
        if (e.sect == cursect) {
            long disp = e.v - (long)here;
            if (final && (disp < -32768L || disp > 32767L))
                error("dbcc out of range%s", NULL);
            emit_word((unsigned long)disp & 0xffff);
        } else {
            if (e.sect == SECT_ABS)
                error("bad dbcc target%s", NULL);
            add_reloc(here, R_68K_PC16, &e);
            emit_word(0);
        }
        return 1;
    }

    for (i = 0; i < nops; i++) {
        if (!parse_operand(parts[i], &o[i])) {
            bad_operands(mn);
            return 1;
        }
        fix_abs(&o[i]);
    }

    /* no operand instructions */
    if (nops == 0) {
        static const struct { const char *n; unsigned short op; } simple[] = {
            {"rts", 0x4e75}, {"nop", 0x4e71}, {"rte", 0x4e73}, {"rtr", 0x4e77},
            {"reset", 0x4e70}, {"trapv", 0x4e76}, {"illegal", 0x4afc}, {NULL, 0}
        };
        for (i = 0; simple[i].n; i++)
            if (!strcmp(base, simple[i].n)) {
                emit_word(simple[i].op);
                return 1;
            }
    }

    if (!strcmp(base, "move") || !strcmp(base, "movea")) {
        int sc = size_from_suffix(sfx, 1);
        if (sc < 0 || nops != 2) { bad_operands(mn); return 1; }
        set_size(sc);
        if (d->mode == M_CCR || d->mode == M_SR) {
            if (!(ea_class(s) & EA_DATA)) { bad_operands(mn); return 1; }
            set_size(1);
            emit_op((d->mode == M_CCR ? 0x44c0 : 0x46c0) | ea_bits(s), s, 2, NULL, 0);
            return 1;
        }
        if (s->mode == M_SR) {
            if (!is_data_alterable(d)) { bad_operands(mn); return 1; }
            emit_op(0x40c0 | ea_bits(d), d, 2, NULL, 0);
            return 1;
        }
        if (s->mode == M_USP && d->mode == M_AREG) { emit_word(0x4e68 | d->reg); return 1; }
        if (d->mode == M_USP && s->mode == M_AREG) { emit_word(0x4e60 | s->reg); return 1; }
        if (!ea_class(s) || s->mode == M_REGLIST) { bad_operands(mn); return 1; }
        if (d->mode == M_AREG) {
            if (sc == 0) { bad_operands(mn); return 1; }
        } else if (!is_data_alterable(d)) {
            bad_operands(mn);
            return 1;
        }
        if (s->mode == M_AREG && sc == 0) { bad_operands(mn); return 1; }
        /* move.l #n,dN with -128 <= n <= 127 is a moveq (GNU as does that too) */
        if (sc == 2 && s->mode == M_IMM && d->mode == M_DREG && quick_value(s, &v) && v >= -128 && v <= 127) {
            emit_word(0x7000 | ((unsigned long)d->reg << 9) | ((unsigned long)v & 0xff));
            return 1;
        }
        {
            int db = ea_bits(d);
            opc = (sc == 0 ? 0x1000 : sc == 1 ? 0x3000 : 0x2000)
                | ((unsigned long)(db & 7) << 9) | ((unsigned long)(db >> 3) << 6) | ea_bits(s);
            emit_op(opc, s, opsize, d, opsize);
        }
        return 1;
    }
    if (!strcmp(base, "moveq")) {
        struct expr e;
        if (nops != 2 || s->mode != M_IMM || d->mode != M_DREG) { bad_operands(mn); return 1; }
        eval(s->text, &e);
        if (e.sect != SECT_ABS)
            error("moveq needs a constant%s", NULL);
        else if (e.v < -128 || e.v > 255)
            error("moveq value out of range%s", NULL);
        emit_word(0x7000 | (d->reg << 9) | ((unsigned long)e.v & 0xff));
        return 1;
    }
    if (!strcmp(base, "movem")) {
        int sc = size_from_suffix(sfx, 1), tomem;
        unsigned long mask;
        struct operand *regs, *mem;
        if ((sc != 1 && sc != 2) || nops != 2) { bad_operands(mn); return 1; }
        set_size(sc);
        /* a single register is a register list too */
        for (i = 0; i < 2; i++)
            if (o[i].mode == M_DREG || o[i].mode == M_AREG) {
                o[i].mask = 1 << (o[i].mode == M_AREG ? o[i].reg + 8 : o[i].reg);
                o[i].mode = M_REGLIST;
            }
        if (s->mode == M_REGLIST || (s->mode == M_IMM && d->mode != M_REGLIST && d->mode != M_IMM)) {
            tomem = 1; regs = s; mem = d;
        } else {
            tomem = 0; regs = d; mem = s;
        }
        if (tomem) {
            if (!(mem->mode == M_PREDEC || ((ea_class(mem) & EA_CONTROL) && (ea_class(mem) & EA_ALTER)))) { bad_operands(mn); return 1; }
        } else {
            if (!(mem->mode == M_POSTINC || (ea_class(mem) & EA_CONTROL))) { bad_operands(mn); return 1; }
        }
        if (regs->mode == M_IMM) {
            struct expr e;
            eval(regs->text, &e);
            if (e.sect != SECT_ABS) {
                error("movem mask is not a constant%s", NULL);
                e.v = 0;
            }
            mask = (unsigned long)e.v & 0xffff;
        } else if (regs->mode == M_REGLIST) {
            mask = regs->mask;
            if (mem->mode == M_PREDEC) {
                unsigned long r = 0;
                for (i = 0; i < 16; i++)
                    if (mask & (1UL << i))
                        r |= 1UL << (15 - i);
                mask = r;
            }
        } else {
            bad_operands(mn);
            return 1;
        }
        emit_word((tomem ? 0x4880 : 0x4c80) | (sc == 2 ? 0x40 : 0) | ea_bits(mem));
        emit_word(mask);
        ea_ext(mem, 0);
        return 1;
    }
    if (!strcmp(base, "lea")) {
        if (nops != 2 || !(ea_class(s) & EA_CONTROL) || d->mode != M_AREG) { bad_operands(mn); return 1; }
        emit_op(0x41c0 | (d->reg << 9) | ea_bits(s), s, 0, NULL, 0);
        return 1;
    }
    if (!strcmp(base, "pea") || !strcmp(base, "jmp") || !strcmp(base, "jsr")) {
        if (nops != 1 || !(ea_class(s) & EA_CONTROL)) { bad_operands(mn); return 1; }
        opc = base[0] == 'p' ? 0x4840 : base[1] == 'm' ? 0x4ec0 : 0x4e80;
        emit_op(opc | ea_bits(s), s, 0, NULL, 0);
        return 1;
    }
    if (!strcmp(base, "clr") || !strcmp(base, "neg") || !strcmp(base, "negx") || !strcmp(base, "not") || !strcmp(base, "tst")) {
        int sc = size_from_suffix(sfx, 1);
        if (sc < 0 || nops != 1) { bad_operands(mn); return 1; }
        set_size(sc);
        if (base[0] == 't') {
            if (!(ea_class(s) & EA_ALTER) || s->mode == M_AREG) {
                if (!(ea_class(s) & EA_DATA) || s->mode == M_IMM) { bad_operands(mn); return 1; }
                error("tst of this addressing mode needs a 68020%s", NULL);
            }
            opc = 0x4a00;
        } else {
            if (!is_data_alterable(s)) { bad_operands(mn); return 1; }
            opc = base[0] == 'c' ? 0x4200 : base[1] == 'o' ? 0x4600 : base[3] == 'x' ? 0x4000 : 0x4400;
        }
        emit_op(opc | (sc << 6) | ea_bits(s), s, opsize, NULL, 0);
        return 1;
    }
    if (!strcmp(base, "ext")) {
        int sc = size_from_suffix(sfx, 1);
        if ((sc != 1 && sc != 2) || nops != 1 || s->mode != M_DREG) { bad_operands(mn); return 1; }
        emit_word((sc == 1 ? 0x4880 : 0x48c0) | s->reg);
        return 1;
    }
    if (!strcmp(base, "swap")) {
        if (nops != 1 || s->mode != M_DREG) { bad_operands(mn); return 1; }
        emit_word(0x4840 | s->reg);
        return 1;
    }
    if (!strcmp(base, "link")) {
        if (nops != 2 || s->mode != M_AREG || d->mode != M_IMM) { bad_operands(mn); return 1; }
        emit_word(0x4e50 | s->reg);
        ea_ext(d, 2);
        return 1;
    }
    if (!strcmp(base, "unlk")) {
        if (nops != 1 || s->mode != M_AREG) { bad_operands(mn); return 1; }
        emit_word(0x4e58 | s->reg);
        return 1;
    }
    if (!strcmp(base, "trap")) {
        struct expr e;
        if (nops != 1 || s->mode != M_IMM) { bad_operands(mn); return 1; }
        eval(s->text, &e);
        if (e.sect != SECT_ABS || e.v < 0 || e.v > 15)
            error("bad trap number%s", NULL);
        emit_word(0x4e40 | ((unsigned long)e.v & 15));
        return 1;
    }
    if (!strcmp(base, "stop")) {
        if (nops != 1 || s->mode != M_IMM) { bad_operands(mn); return 1; }
        emit_word(0x4e72);
        ea_ext(s, 2);
        return 1;
    }
    if (!strcmp(base, "exg")) {
        if (nops != 2) { bad_operands(mn); return 1; }
        if (s->mode == M_DREG && d->mode == M_DREG)
            emit_word(0xc140 | (s->reg << 9) | d->reg);
        else if (s->mode == M_AREG && d->mode == M_AREG)
            emit_word(0xc148 | (s->reg << 9) | d->reg);
        else if (s->mode == M_DREG && d->mode == M_AREG)
            emit_word(0xc188 | (s->reg << 9) | d->reg);
        else if (s->mode == M_AREG && d->mode == M_DREG)
            emit_word(0xc188 | (d->reg << 9) | s->reg);
        else
            bad_operands(mn);
        return 1;
    }
    if (!strcmp(base, "add") || !strcmp(base, "sub") || !strcmp(base, "adda") || !strcmp(base, "suba")
        || !strcmp(base, "addi") || !strcmp(base, "subi") || !strcmp(base, "addq") || !strcmp(base, "subq")) {
        int sc = size_from_suffix(sfx, 1), issub = base[0] == 's';
        int variant = base[3];          /* 0, 'a', 'i', 'q' */
        if (sc < 0 || nops != 2) { bad_operands(mn); return 1; }
        set_size(sc);
        if (variant == 'q' || (variant == 0 && s->mode == M_IMM && quick_value(s, &v) && v >= 1 && v <= 8)) {
            struct expr e;
            if (s->mode != M_IMM || !(ea_class(d) & EA_ALTER) || (d->mode == M_AREG && sc == 0)) { bad_operands(mn); return 1; }
            eval(s->text, &e);
            if (e.sect != SECT_ABS || e.v < 1 || e.v > 8)
                error("quick value must be 1..8%s", NULL);
            emit_op((issub ? 0x5100 : 0x5000) | (((unsigned long)e.v & 7) << 9) | (sc << 6) | ea_bits(d), d, opsize, NULL, 0);
            return 1;
        }
        if (d->mode == M_AREG || variant == 'a') {
            if (d->mode != M_AREG || sc == 0 || !ea_class(s)) { bad_operands(mn); return 1; }
            emit_op((issub ? 0x9000 : 0xd000) | (d->reg << 9) | (sc == 2 ? 0x1c0 : 0xc0) | ea_bits(s), s, opsize, NULL, 0);
            return 1;
        }
        if (s->mode == M_IMM && (variant == 'i' || variant == 0)) {
            if (!is_data_alterable(d)) { bad_operands(mn); return 1; }
            emit_op((issub ? 0x0400 : 0x0600) | (sc << 6) | ea_bits(d), s, opsize, d, opsize);
            return 1;
        }
        if (variant) { bad_operands(mn); return 1; }
        if (d->mode == M_DREG) {
            if (!ea_class(s) || (s->mode == M_AREG && sc == 0)) { bad_operands(mn); return 1; }
            emit_op((issub ? 0x9000 : 0xd000) | (d->reg << 9) | (sc << 6) | ea_bits(s), s, opsize, NULL, 0);
            return 1;
        }
        if (s->mode == M_DREG && is_alterable_mem(d)) {
            emit_op((issub ? 0x9100 : 0xd100) | (s->reg << 9) | (sc << 6) | ea_bits(d), d, opsize, NULL, 0);
            return 1;
        }
        bad_operands(mn);
        return 1;
    }
    if (!strcmp(base, "addx") || !strcmp(base, "subx") || !strcmp(base, "abcd") || !strcmp(base, "sbcd")) {
        int sc = size_from_suffix(sfx, (base[1] == 'b' || (base[0] == 'a' && base[1] == 'b')) ? 0 : 1);
        if (base[1] == 'b' || base[3] == 'd')
            sc = 0;
        if (sc < 0 || nops != 2) { bad_operands(mn); return 1; }
        if (base[3] == 'x')
            opc = (base[0] == 's' ? 0x9100 : 0xd100) | (sc << 6);
        else
            opc = base[0] == 's' ? 0x8100 : 0xc100;
        if (s->mode == M_DREG && d->mode == M_DREG)
            emit_word(opc | (d->reg << 9) | s->reg);
        else if (s->mode == M_PREDEC && d->mode == M_PREDEC)
            emit_word(opc | 8 | (d->reg << 9) | s->reg);
        else
            bad_operands(mn);
        return 1;
    }
    if (!strcmp(base, "cmp") || !strcmp(base, "cmpa") || !strcmp(base, "cmpi") || !strcmp(base, "cmpm")) {
        int sc = size_from_suffix(sfx, 1);
        if (sc < 0 || nops != 2) { bad_operands(mn); return 1; }
        set_size(sc);
        if (base[3] == 'm' || (s->mode == M_POSTINC && d->mode == M_POSTINC)) {
            if (s->mode != M_POSTINC || d->mode != M_POSTINC) { bad_operands(mn); return 1; }
            emit_word(0xb108 | (d->reg << 9) | (sc << 6) | s->reg);
            return 1;
        }
        if (d->mode == M_AREG) {
            if (sc == 0 || !ea_class(s)) { bad_operands(mn); return 1; }
            emit_op(0xb000 | (d->reg << 9) | (sc == 2 ? 0x1c0 : 0xc0) | ea_bits(s), s, opsize, NULL, 0);
            return 1;
        }
        if (s->mode == M_IMM && (base[3] == 'i' || is_data_alterable(d))) {
            if (!is_data_alterable(d)) { bad_operands(mn); return 1; }
            emit_op(0x0c00 | (sc << 6) | ea_bits(d), s, opsize, d, opsize);
            return 1;
        }
        if (base[3]) { bad_operands(mn); return 1; }
        if (d->mode == M_DREG && ea_class(s) && !(s->mode == M_AREG && sc == 0)) {
            emit_op(0xb000 | (d->reg << 9) | (sc << 6) | ea_bits(s), s, opsize, NULL, 0);
            return 1;
        }
        bad_operands(mn);
        return 1;
    }
    if (!strcmp(base, "and") || !strcmp(base, "or") || !strcmp(base, "eor")
        || !strcmp(base, "andi") || !strcmp(base, "ori") || !strcmp(base, "eori")) {
        int sc = size_from_suffix(sfx, 1);
        int kind = base[0] == 'a' ? 0 : base[0] == 'o' ? 1 : 2;
        static const unsigned short immop[] = {0x0200, 0x0000, 0x0a00};
        static const unsigned short regop[] = {0xc000, 0x8000, 0xb000};
        if (sc < 0 || nops != 2) { bad_operands(mn); return 1; }
        set_size(sc);
        if (d->mode == M_CCR || d->mode == M_SR) {
            if (s->mode != M_IMM) { bad_operands(mn); return 1; }
            emit_word(immop[kind] | (d->mode == M_CCR ? 0x3c : 0x7c));
            ea_ext(s, d->mode == M_CCR ? 1 : 2);
            return 1;
        }
        if (s->mode == M_IMM) {
            if (!is_data_alterable(d)) { bad_operands(mn); return 1; }
            emit_op(immop[kind] | (sc << 6) | ea_bits(d), s, opsize, d, opsize);
            return 1;
        }
        if (base[strlen(base) - 1] == 'i') { bad_operands(mn); return 1; }
        if (kind != 2 && d->mode == M_DREG && (ea_class(s) & EA_DATA)) {
            emit_op(regop[kind] | (d->reg << 9) | (sc << 6) | ea_bits(s), s, opsize, NULL, 0);
            return 1;
        }
        if (s->mode == M_DREG && (kind == 2 ? is_data_alterable(d) : is_alterable_mem(d))) {
            emit_op(regop[kind] | 0x100 | (s->reg << 9) | (sc << 6) | ea_bits(d), d, opsize, NULL, 0);
            return 1;
        }
        bad_operands(mn);
        return 1;
    }
    if (!strcmp(base, "muls") || !strcmp(base, "mulu") || !strcmp(base, "divs") || !strcmp(base, "divu")) {
        if ((sfx && sfx != 'w') || nops != 2 || d->mode != M_DREG || !(ea_class(s) & EA_DATA)) {
            if (sfx == 'l')
                error("32 bit multiply/divide needs a 68020%s", NULL);
            else
                bad_operands(mn);
            return 1;
        }
        opc = base[0] == 'm' ? (base[3] == 's' ? 0xc1c0 : 0xc0c0) : (base[3] == 's' ? 0x81c0 : 0x80c0);
        emit_op(opc | (d->reg << 9) | ea_bits(s), s, 2, NULL, 0);
        return 1;
    }
    if (!strcmp(base, "chk")) {
        if (nops != 2 || d->mode != M_DREG || !(ea_class(s) & EA_DATA)) { bad_operands(mn); return 1; }
        emit_op(0x4180 | (d->reg << 9) | ea_bits(s), s, 2, NULL, 0);
        return 1;
    }
    if (!strcmp(base, "tas") || !strcmp(base, "nbcd")) {
        if (nops != 1 || !is_data_alterable(s)) { bad_operands(mn); return 1; }
        emit_op((base[0] == 't' ? 0x4ac0 : 0x4800) | ea_bits(s), s, 0, NULL, 0);
        return 1;
    }
    {
        static const char *shifts[] = {"asr", "asl", "lsr", "lsl", "roxr", "roxl", "ror", "rol", NULL};
        for (i = 0; shifts[i]; i++)
            if (!strcmp(base, shifts[i]))
                break;
        if (shifts[i]) {
            int type = i >> 1, dir = i & 1;
            int sc = size_from_suffix(sfx, 1);
            if (sc < 0) { bad_operands(mn); return 1; }
            if (nops == 1 && s->mode == M_DREG) {
                emit_word(0xe000 | (1 << 9) | (dir << 8) | (sc << 6) | (type << 3) | s->reg);
                return 1;
            }
            if (nops == 1) {
                if (!is_alterable_mem(s) || sc != 1) { bad_operands(mn); return 1; }
                emit_op(0xe0c0 | (type << 9) | (dir << 8) | ea_bits(s), s, 0, NULL, 0);
                return 1;
            }
            if (nops != 2 || d->mode != M_DREG) { bad_operands(mn); return 1; }
            if (s->mode == M_DREG) {
                emit_word(0xe000 | (s->reg << 9) | (dir << 8) | (sc << 6) | 0x20 | (type << 3) | d->reg);
                return 1;
            }
            if (s->mode == M_IMM) {
                struct expr e;
                eval(s->text, &e);
                if (e.sect != SECT_ABS || e.v < 1 || e.v > 8)
                    error("shift count must be 1..8%s", NULL);
                emit_word(0xe000 | (((unsigned long)e.v & 7) << 9) | (dir << 8) | (sc << 6) | (type << 3) | d->reg);
                return 1;
            }
            bad_operands(mn);
            return 1;
        }
    }
    if (!strcmp(base, "btst") || !strcmp(base, "bchg") || !strcmp(base, "bclr") || !strcmp(base, "bset")) {
        int bop = base[1] == 't' ? 0 : base[1] == 'c' && base[2] == 'h' ? 1 : base[2] == 'l' ? 2 : 3;
        if (nops != 2) { bad_operands(mn); return 1; }
        if (bop == 0 ? !(ea_class(d) & EA_DATA) : !is_data_alterable(d)) { bad_operands(mn); return 1; }
        if (s->mode == M_DREG) {
            emit_op(0x0100 | (s->reg << 9) | (bop << 6) | ea_bits(d), d, 1, NULL, 0);
            return 1;
        }
        if (s->mode == M_IMM) {
            emit_word(0x0800 | (bop << 6) | ea_bits(d));
            ea_ext(s, 1);
            ea_ext(d, 1);
            return 1;
        }
        bad_operands(mn);
        return 1;
    }
    if (base[0] == 's' && (cc = cond_code(base + 1)) >= 0 && strlen(base) <= 3) {
        if (nops != 1 || !is_data_alterable(s)) { bad_operands(mn); return 1; }
        emit_op(0x50c0 | (cc << 8) | ea_bits(s), s, 1, NULL, 0);
        return 1;
    }
    if (!strcmp(base, "movep")) {
        int sc = size_from_suffix(sfx, 1);
        if ((sc != 1 && sc != 2) || nops != 2) { bad_operands(mn); return 1; }
        if (s->mode == M_DREG && (d->mode == M_DISP || d->mode == M_IND)) {
            if (d->mode == M_IND) { d->mode = M_DISP; d->text = zero_text; }
            emit_word(0x0188 | (s->reg << 9) | (sc == 2 ? 0x40 : 0) | d->reg);
            ea_ext(d, 2);
        } else if (d->mode == M_DREG && (s->mode == M_DISP || s->mode == M_IND)) {
            if (s->mode == M_IND) { s->mode = M_DISP; s->text = zero_text; }
            emit_word(0x0108 | (d->reg << 9) | (sc == 2 ? 0x40 : 0) | s->reg);
            ea_ext(s, 2);
        } else {
            bad_operands(mn);
        }
        return 1;
    }
    return 0;
}

