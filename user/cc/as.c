/* ELF output                                                          */

static unsigned char *obuf;
static unsigned long olen, ocap;

static void oput(const void *p, unsigned long n)
{
    if (olen + n > ocap) {
        ocap = ocap ? ocap * 2 : 65536;
        while (ocap < olen + n)
            ocap *= 2;
        obuf = xrealloc(obuf, ocap);
    }
    memcpy(obuf + olen, p, n);
    olen += n;
}

static void oput8(int v) { unsigned char c = (unsigned char)v; oput(&c, 1); }
static void oput16(unsigned long v) { oput8((int)(v >> 8)); oput8((int)v); }
static void oput32(unsigned long v) { oput16((v >> 16) & 0xffff); oput16(v & 0xffff); }
static void oalign(int a) { while (olen % a) oput8(0); }

static char *strtab;
static unsigned long strtablen, strtabcap;

static unsigned long addstr(char *buf_unused, const char *s)
{
    unsigned long off = strtablen, n = strlen(s) + 1;
    (void)buf_unused;
    if (strtablen + n > strtabcap) {
        strtabcap = strtabcap ? strtabcap * 2 : 4096;
        while (strtabcap < strtablen + n)
            strtabcap *= 2;
        strtab = xrealloc(strtab, strtabcap);
    }
    memcpy(strtab + strtablen, s, n);
    strtablen += n;
    return off;
}

static const char *outname(const char *n)
{
    if (!keep_underscore && n[0] == '_')
        return n + 1;
    return n;
}

static void write_elf(const char *fname)
{
    struct sh {
        unsigned long name, type, flags, addr, offset, size, link, info, align, entsize;
    } shdr[3 * MAXSECT + 4];
    int nsh = 0, i, nsyms, firstglobal;
    unsigned long shstr_len = 0;
    static char shstr[2048];
    struct symbol *s;
    int symtab_ndx, strtab_ndx, shstrtab_ndx;
    FILE *f;

    memset(shdr, 0, sizeof(shdr));
    shstr[0] = 0;
    shstr_len = 1;
#define ADDSHSTR(str) (memcpy(shstr + shstr_len, str, strlen(str) + 1), shstr_len += strlen(str) + 1, shstr_len - strlen(str) - 1)

    strtablen = 0;
    addstr(NULL, "");

    /* ELF header placeholder */
    for (i = 0; i < 52; i++)
        oput8(0);

    nsh = 1;    /* null section */
    for (i = 0; i < nsects; i++) {
        struct section *sc = &sects[i];
        sc->shndx = nsh;
        shdr[nsh].name = ADDSHSTR(sc->name);
        shdr[nsh].type = sc->type;
        shdr[nsh].flags = sc->flags;
        shdr[nsh].align = sc->align;
        shdr[nsh].size = sc->size;
        if (sc->type != SHT_NOBITS) {
            oalign(4);
            shdr[nsh].offset = olen;
            if (sc->size)
                oput(sc->data, sc->size);
        } else {
            shdr[nsh].offset = olen;
        }
        nsh++;
    }

    /* symbols: null, section symbols, then globals */
    nsyms = 1;
    for (i = 0; i < nsects; i++)
        if (sects[i].shndx)
            sects[i].symndx = nsyms++;
    firstglobal = nsyms;
    for (s = symlist; s; s = s->link) {
        s->elfndx = 0;
        if ((s->flags & SYM_COMMON)
            || ((s->flags & SYM_GLOBAL) && (s->flags & SYM_DEFINED))
            || (!(s->flags & SYM_DEFINED) && (s->flags & SYM_USED)))
            s->elfndx = nsyms++;
        else if ((s->flags & SYM_DEFINED) && (s->flags & SYM_USED) && s->sect == SECT_ABS)
            s->elfndx = nsyms++;
    }

    /* relocation sections */
    for (i = 0; i < nsects; i++) {
        struct section *sc = &sects[i];
        int j;
        char rname[80];
        if (!sc->shndx || !sc->nrel)
            continue;
        oalign(4);
        strcpy(rname, ".rela");
        strncat(rname, sc->name, sizeof(rname) - 6);
        shdr[nsh].name = ADDSHSTR(rname);
        shdr[nsh].type = SHT_RELA;
        shdr[nsh].offset = olen;
        shdr[nsh].size = sc->nrel * 12UL;
        shdr[nsh].info = sc->shndx;
        shdr[nsh].align = 4;
        shdr[nsh].entsize = 12;
        sc->relndx = nsh;
        for (j = 0; j < sc->nrel; j++) {
            struct reloc *r = &sc->rel[j];
            unsigned long symi;
            long addend = r->addend;
            if (r->sym) {
                symi = r->sym->elfndx;
                if (!symi)
                    fatal("internal error: relocation against a symbol not in the table");
            } else {
                symi = sects[r->sect].symndx;
            }
            oput32(r->off);
            oput32((symi << 8) | (unsigned long)r->type);
            oput32((unsigned long)addend);
        }
        nsh++;
    }

    /* symbol table */
    oalign(4);
    symtab_ndx = nsh;
    shdr[nsh].name = ADDSHSTR(".symtab");
    shdr[nsh].type = SHT_SYMTAB;
    shdr[nsh].offset = olen;
    shdr[nsh].size = nsyms * 16UL;
    shdr[nsh].info = firstglobal;
    shdr[nsh].align = 4;
    shdr[nsh].entsize = 16;
    nsh++;
    /* null */
    oput32(0); oput32(0); oput32(0); oput8(0); oput8(0); oput16(0);
    for (i = 0; i < nsects; i++) {
        if (!sects[i].shndx)
            continue;
        oput32(0); oput32(0); oput32(0);
        oput8((STB_LOCAL << 4) | STT_SECTION);
        oput8(0);
        oput16(sects[i].shndx);
    }
    for (s = symlist; s; s = s->link) {
        unsigned long nameoff, shndx, value, size = 0;
        if (!s->elfndx)
            continue;
        nameoff = addstr(NULL, outname(s->name));
        if (s->flags & SYM_COMMON) {
            shndx = SHN_COMMON;
            value = s->align;
            size = s->size;
        } else if (s->flags & SYM_DEFINED) {
            if (s->sect == SECT_ABS) {
                shndx = SHN_ABS;
            } else {
                shndx = sects[s->sect].shndx;
            }
            value = s->value;
        } else {
            shndx = SHN_UNDEF;
            value = 0;
        }
        oput32(nameoff);
        oput32(value);
        oput32(size);
        oput8((STB_GLOBAL << 4) | STT_NOTYPE);
        oput8(0);
        oput16(shndx);
    }
    /* string table */
    strtab_ndx = nsh;
    shdr[nsh].name = ADDSHSTR(".strtab");
    shdr[nsh].type = SHT_STRTAB;
    shdr[nsh].offset = olen;
    shdr[nsh].size = strtablen;
    shdr[nsh].align = 1;
    oput(strtab, strtablen);
    nsh++;
    shstrtab_ndx = nsh;
    shdr[nsh].name = ADDSHSTR(".shstrtab");
    shdr[nsh].type = SHT_STRTAB;
    shdr[nsh].offset = olen;
    shdr[nsh].size = shstr_len;
    shdr[nsh].align = 1;
    oput(shstr, shstr_len);
    nsh++;

    shdr[symtab_ndx].link = strtab_ndx;
    for (i = 0; i < nsects; i++)
        if (sects[i].relndx)
            shdr[sects[i].relndx].link = symtab_ndx;

    /* section headers */
    oalign(4);
    {
        unsigned long shoff = olen;
        unsigned long save;
        for (i = 0; i < nsh; i++) {
            oput32(shdr[i].name);
            oput32(shdr[i].type);
            oput32(shdr[i].flags);
            oput32(shdr[i].addr);
            oput32(shdr[i].offset);
            oput32(shdr[i].size);
            oput32(shdr[i].link);
            oput32(shdr[i].info);
            oput32(shdr[i].align);
            oput32(shdr[i].entsize);
        }
        /* ELF header */
        save = olen;
        olen = 0;
        oput8(0x7f); oput8('E'); oput8('L'); oput8('F');
        oput8(1);       /* 32 bit */
        oput8(2);       /* big endian */
        oput8(1);       /* version */
        for (i = 7; i < 16; i++)
            oput8(0);
        oput16(ET_REL);
        oput16(EM_68K);
        oput32(1);
        oput32(0);      /* entry */
        oput32(0);      /* phoff */
        oput32(shoff);
        oput32(0);      /* flags */
        oput16(52);
        oput16(0);
        oput16(0);
        oput16(40);
        oput16(nsh);
        oput16(shstrtab_ndx);
        olen = save;
    }
#undef ADDSHSTR

    f = fopen(fname, "wb");
    if (!f) {
        perror(fname);
        exit(1);
    }
    if (fwrite(obuf, 1, olen, f) != olen || fclose(f) != 0) {
        perror(fname);
        remove(fname);
        exit(1);
    }
}

