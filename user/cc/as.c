static void read_source(const char *fname)
{
    FILE *f = strcmp(fname, "-") ? fopen(fname, "rb") : stdin;
    char *buf, *p;
    unsigned long len = 0, cap = 65536;
    int n, i;
    if (!f) {
        perror(fname);
        exit(1);
    }
    buf = xmalloc(cap + 1);
    while ((n = (int)fread(buf + len, 1, cap - len, f)) > 0) {
        len += n;
        if (len == cap) {
            cap *= 2;
            buf = xrealloc(buf, cap + 1);
        }
    }
    if (f != stdin)
        fclose(f);
    buf[len] = 0;
    nlines = 1;
    for (p = buf; *p; p++)
        if (*p == '\n')
            nlines++;
    lines = xmalloc(nlines * sizeof(char *));
    i = 0;
    lines[i++] = buf;
    for (p = buf; *p; p++) {
        if (*p == '\n') {
            *p = 0;
            if (p > buf && p[-1] == '\r')
                p[-1] = 0;
            lines[i++] = p + 1;
        }
    }
    nlines = i;
    linfo = xmalloc(nlines * sizeof(struct lineinfo));
    memset(linfo, 0, nlines * sizeof(struct lineinfo));
}

static void usage(void)
{
    fprintf(stderr, "usage: as [-u] [-o output.o] input.s\n"
                    "  -u   keep leading underscores of symbol names\n");
    exit(1);
}

int main(int argc, char **argv)
{
    const char *in = NULL;
    char *out = NULL;
    int i;

    for (i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "-o") && i + 1 < argc)
            out = argv[++i];
        else if (!strcmp(argv[i], "-u"))
            keep_underscore = 1;
        else if (!strncmp(argv[i], "-m", 2) || !strcmp(argv[i], "--register-prefix-optional"))
            ;   /* accepted for compatibility */
        else if (argv[i][0] == '-' && argv[i][1])
            usage();
        else if (!in)
            in = argv[i];
        else
            usage();
    }
    if (!in)
        usage();
    if (!out) {
        const char *b = strrchr(in, '/');
        int l;
        b = b ? b + 1 : in;
        l = (int)strlen(b);
        out = xmalloc(l + 3);
        strcpy(out, b);
        if (l > 2 && out[l - 2] == '.')
            out[l - 1] = 'o';
        else
            strcat(out, ".o");
    }
    srcname = (char *)in;
    read_source(in);

    find_section(".text", 1);
    find_section(".data", 1);
    find_section(".bss", 1);

    /* sizing passes until nothing moves any more */
    for (pass = 0; pass < 40; pass++) {
        run_pass();
        if (pass > 0 && !changed && !cur_relax_changed)
            break;
    }
    if (pass >= 40)
        fatal("branch relaxation did not converge");

    /* final pass: emit the bytes */
    pass++;
    final = 1;
    for (i = 0; i < nsects; i++) {
        sects[i].size = 0;
        sects[i].nrel = 0;
    }
    run_pass();
    if (changed || cur_relax_changed) {
        fprintf(stderr, "%s: warning: layout changed in the final pass\n", srcname);
    }

    if (nerrors)
        return 1;
    write_elf(out);
    return 0;
}
