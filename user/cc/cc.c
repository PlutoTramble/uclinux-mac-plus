/*
 * cc - compiler driver for uClinux on the Macintosh Plus.
 *
 * Runs cpp (C -> preprocessed C), cc1 (GCC 1.42: -> assembly), as (assembly
 * -> ELF object) and ld (objects + libraries -> bFLT executable), one
 * process after the other: only one stage is in RAM at a time, the stages
 * talk through temporary files in /var/tmp.
 *
 * usage: cc [-c] [-S] [-E] [-o out] [-O[n]] [-g] [-I dir] [-D name[=val]]
 *           [-U name] [-L dir] [-l name] [-v] [-s stack] files.c|.s|.o ...
 *
 * There is no fork() without an MMU, so processes are started with vfork()
 * followed immediately by exec.
 *
 * Written to be built with gcc 2.95 (C89) as well as a modern host compiler.
 * The install locations can be changed at build time with -DCC_BINDIR=...,
 * -DCC_LIBDIR=... and -DCC_INCDIR=... (used by the host test).
 *
 * Generated by LLM
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <errno.h>
#include <sys/types.h>
#include <sys/wait.h>
#include <sys/stat.h>

#ifndef CC_BINDIR
#define CC_BINDIR "/usr/bin"
#endif
#ifndef CC_LIBDIR
#define CC_LIBDIR "/usr/lib"
#endif
#ifndef CC_INCDIR
#define CC_INCDIR "/usr/include"
#endif
#ifndef CC_TMPDIR
#define CC_TMPDIR "/var/tmp"
#endif

#define MAXARGS 256

struct vec {
    char *a[MAXARGS];
    int n;
};

/* the vectors are static: without an MMU the stack is small and fixed */
static struct vec cflags, ldargs, libs, inputs, objs, cmd;

static int verbose;
static char *tmpfiles[256];
static int ntmp;

static void *xmalloc(unsigned long n)
{
    void *p = malloc(n ? n : 1);
    if (!p) {
        fprintf(stderr, "cc: out of memory\n");
        exit(1);
    }
    return p;
}

static char *cat(const char *a, const char *b, const char *c)
{
    char *p = xmalloc(strlen(a) + strlen(b) + strlen(c) + 1);
    strcpy(p, a);
    strcat(p, b);
    strcat(p, c);
    return p;
}

static void push(struct vec *v, const char *s)
{
    if (v->n >= MAXARGS - 1) {
        fprintf(stderr, "cc: too many arguments\n");
        exit(1);
    }
    v->a[v->n++] = (char *)s;
    v->a[v->n] = NULL;
}

static void cleanup(void)
{
    int i;
    if (verbose)
        return;
    for (i = 0; i < ntmp; i++)
        unlink(tmpfiles[i]);
    ntmp = 0;
}

static void die(int code)
{
    cleanup();
    exit(code);
}

static int run(struct vec *v)
{
    pid_t pid;
    int status, i;
    if (verbose) {
        for (i = 0; i < v->n; i++)
            fprintf(stderr, "%s%s", i ? " " : "", v->a[i]);
        fputc('\n', stderr);
    }
    fflush(stdout);
    fflush(stderr);
    pid = vfork();
    if (pid < 0) {
        fprintf(stderr, "cc: cannot start %s: %s\n", v->a[0], strerror(errno));
        return 1;
    }
    if (pid == 0) {
        execv(v->a[0], v->a);
        _exit(127);
    }
    while (waitpid(pid, &status, 0) < 0)
        if (errno != EINTR)
            return 1;
    if (WIFEXITED(status)) {
        if (WEXITSTATUS(status) == 127)
            fprintf(stderr, "cc: cannot execute %s\n", v->a[0]);
        return WEXITSTATUS(status);
    }
    if (WIFSIGNALED(status)) {
        int sig = WTERMSIG(status);
        const char *name = NULL;
        switch (sig) {
        case 4: name = "SIGILL"; break;
        case 6: name = "SIGABRT"; break;
        case 7: name = "SIGBUS"; break;
        case 8: name = "SIGFPE"; break;
        case 9: name = "SIGKILL"; break;
        case 11: name = "SIGSEGV"; break;
        case 15: name = "SIGTERM"; break;
        }
        if (name)
            fprintf(stderr, "cc: %s killed by %s%s\n", v->a[0], name,
                    (sig == 9 || sig == 11) ? " (out of memory?)" : "");
        else
            fprintf(stderr, "cc: %s killed by signal %d\n", v->a[0], sig);
    } else {
        fprintf(stderr, "cc: %s stopped abnormally\n", v->a[0]);
    }
    return 1;
}

static char *tmpname(const char *suffix)
{
    static int counter;
    char buf[64];
    char *p;
    sprintf(buf, "/cc%ld-%d", (long)getpid(), counter++);
    p = cat(CC_TMPDIR, buf, suffix);
    if (ntmp < 256)
        tmpfiles[ntmp++] = p;
    return p;
}

static int has_suffix(const char *s, const char *suf)
{
    int ls = (int)strlen(s), lf = (int)strlen(suf);
    return ls > lf && !strcmp(s + ls - lf, suf);
}

static char *replace_suffix(const char *s, const char *suf)
{
    char *p = xmalloc(strlen(s) + strlen(suf) + 1), *dot, *slash;
    strcpy(p, s);
    dot = strrchr(p, '.');
    slash = strrchr(p, '/');
    if (dot && (!slash || dot > slash))
        *dot = 0;
    strcat(p, suf);
    return p;
}

static const char *base_name(const char *s)
{
    const char *p = strrchr(s, '/');
    return p ? p + 1 : s;
}

static void usage(void)
{
    fprintf(stderr,
            "usage: cc [-c] [-S] [-E] [-o out] [-O[n]] [-g] [-I dir] [-D name[=val]]\n"
            "          [-U name] [-L dir] [-l name] [-v] [-s stack] files.c|.s|.o ...\n");
    exit(1);
}

int main(int argc, char **argv)
{
    int stop_o = 0, stop_s = 0, stop_e = 0;
    char *outname = NULL;
    char *optlevel = NULL;
    char *stack = NULL;
    int i, rc;
    char *preproc = CC_BINDIR "/cpp";
    char *compiler = CC_BINDIR "/cc1";
    char *assembler = CC_BINDIR "/as";
    char *linker = CC_BINDIR "/ld";

    memset(&cflags, 0, sizeof(cflags));
    memset(&ldargs, 0, sizeof(ldargs));
    memset(&libs, 0, sizeof(libs));
    memset(&inputs, 0, sizeof(inputs));

    for (i = 1; i < argc; i++) {
        char *a = argv[i];
        if (a[0] != '-' || !a[1]) {
            push(&inputs, a);
            continue;
        }
        switch (a[1]) {
        case 'c': stop_o = 1; break;
        case 'S': stop_s = 1; break;
        case 'E': stop_e = 1; break;
        case 'v': verbose = 1; break;
        case 'g': break;
        case 'w': break;
        case 'W': break;                    /* -Wall etc. */
        case 'f': break;
        case 'm': break;
        case 'o':
            if (a[2]) outname = a + 2;
            else if (i + 1 < argc) outname = argv[++i];
            else usage();
            break;
        case 's':
            if (a[2]) stack = a + 2;
            else if (i + 1 < argc) stack = argv[++i];
            else usage();
            break;
        case 'O':
            optlevel = a[2] ? a + 2 : "1";
            break;
        case 'I': case 'D': case 'U':
            if (a[2]) {
                push(&cflags, a);
            } else if (i + 1 < argc) {
                push(&cflags, cat(a, argv[i + 1], ""));
                i++;
            } else usage();
            break;
        case 'L':
            if (a[2]) {
                push(&ldargs, a);
            } else if (i + 1 < argc) {
                push(&ldargs, cat("-L", argv[i + 1], ""));
                i++;
            } else usage();
            break;
        case 'l':
            if (a[2]) {
                push(&libs, a);
            } else if (i + 1 < argc) {
                push(&libs, cat("-l", argv[i + 1], ""));
                i++;
            } else usage();
            break;
        case 'p':
            if (!strcmp(a, "-pedantic")) break;
            usage();
            break;
        case 'a':
            if (!strncmp(a, "-ansi", 5)) break;
            usage();
            break;
        case 'n':
            usage();
            break;
        default:
            fprintf(stderr, "cc: unknown option %s\n", a);
            return 1;
        }
    }
    if (inputs.n == 0) {
        fprintf(stderr, "cc: no input files\n");
        return 1;
    }
    if ((stop_o || stop_s || stop_e) && outname && inputs.n > 1) {
        fprintf(stderr, "cc: -o with -c, -S or -E needs a single input file\n");
        return 1;
    }

    {
        struct vec *vp = &cmd;
#define v (*vp)
        memset(&objs, 0, sizeof(objs));
        for (i = 0; i < inputs.n; i++) {
            char *in = inputs.a[i];
            char *asmfile = NULL, *objfile = NULL;
            if (has_suffix(in, ".c") || has_suffix(in, ".i")) {
                int k;
                char *ifile = in;
                if (has_suffix(in, ".c")) {
                    /* cpp: in.c -> tmp.i (or stdout / -o file with -E) */
                    memset(&v, 0, sizeof(v));
                    push(&v, preproc);
                    push(&v, "-nostdinc");
                    /* GCC 1.42 does not know these keywords */
                    push(&v, "-D__restrict=");
                    push(&v, "-D__restrict__=");
                    push(&v, "-D__extension__=");
                    push(&v, "-Dmc68000");
                    push(&v, "-D__mc68000__");
                    push(&v, "-D__m68k__");
                    push(&v, "-Dlinux");
                    push(&v, "-D__linux__");
                    push(&v, "-Dunix");
                    push(&v, "-D__uClinux__");
                    push(&v, "-DEMBED");
                    for (k = 0; k < cflags.n; k++)
                        push(&v, cflags.a[k]);
                    push(&v, "-I" CC_LIBDIR "/gcc/include");
                    push(&v, "-I" CC_INCDIR);
                    push(&v, in);
                    if (stop_e) {
                        if (outname)
                            push(&v, outname);
                        rc = run(&v);
                        if (rc) {
                            if (outname) unlink(outname);
                            die(rc);
                        }
                        continue;
                    }
                    ifile = tmpname(".i");
                    push(&v, ifile);
                    rc = run(&v);
                    if (rc) die(rc);
                } else if (stop_e) {
                    continue;           /* already preprocessed */
                }
                /* cc1: tmp.i -> tmp.s */
                if (stop_s)
                    asmfile = outname ? outname : replace_suffix(base_name(in), ".s");
                else
                    asmfile = tmpname(".s");
                memset(&v, 0, sizeof(v));
                push(&v, compiler);
                push(&v, ifile);
                push(&v, "-quiet");
                push(&v, "-dumpbase");
                push(&v, base_name(in));
                if (optlevel && strcmp(optlevel, "0"))
                    push(&v, "-O");
                push(&v, "-o");
                push(&v, asmfile);
                rc = run(&v);
                if (ifile != in && !verbose)
                    unlink(ifile);      /* the disk is small */
                if (rc) {
                    if (stop_s) unlink(asmfile);
                    die(rc);
                }
                if (stop_s)
                    continue;
            } else if (has_suffix(in, ".s") || has_suffix(in, ".S")) {
                asmfile = in;
            } else {
                /* object or archive */
                push(&objs, in);
                continue;
            }
            /* assemble */
            if (stop_o)
                objfile = outname ? outname : replace_suffix(base_name(in), ".o");
            else
                objfile = tmpname(".o");
            memset(&v, 0, sizeof(v));
            push(&v, assembler);
            push(&v, "-o");
            push(&v, objfile);
            push(&v, asmfile);
            rc = run(&v);
            if (rc) {
                if (stop_o) unlink(objfile);
                die(rc);
            }
            push(&objs, objfile);
        }
        if (stop_o || stop_s || stop_e) {
            cleanup();
            return 0;
        }
        /* link */
        {
            int k;
            memset(&v, 0, sizeof(v));
            push(&v, linker);
            push(&v, "-o");
            push(&v, outname ? outname : "a.out");
            if (stack) {
                push(&v, "-s");
                push(&v, stack);
            }
            push(&v, "-L" CC_LIBDIR);
            for (k = 0; k < ldargs.n; k++)
                push(&v, ldargs.a[k]);
            push(&v, CC_LIBDIR "/crt0.o");
            for (k = 0; k < objs.n; k++)
                push(&v, objs.a[k]);
            for (k = 0; k < libs.n; k++)
                push(&v, libs.a[k]);
            push(&v, "-lc");
            push(&v, "-lgcc1");         /* GCC 1.42 only helpers */
            push(&v, "-lgcc");
            rc = run(&v);
            if (rc) {
                unlink(outname ? outname : "a.out");
                die(rc);
            }
            chmod(outname ? outname : "a.out", 0755);
        }
#undef v
    }
    cleanup();
    return 0;
}
